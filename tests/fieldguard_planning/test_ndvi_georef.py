"""Tests for ndvi_georef.py -- THE load-bearing seam (tech-lead's standing flag). Built test-first:
every fixture's expected (lat, lon) below was derived BY HAND (independently of calling the module
under test) with a standalone calculator script and pasted in as a literal constant, with the
derivation shown step-by-step in each test's comments -- not generated by the code being tested.
That is the whole point of this file: a single sign/frame error in ndvi_georef.py must make one of
these numbers wrong, not just internally self-consistent.

Shared constants (from config/ndvi_camera.json / config/field_polygon.json, read once, not
hardcoded a second, possibly-inconsistent way):
  width=640 height=480 horizontal_fov_rad=1.1033  ->  fx=fy=(640/2)/tan(1.1033/2)=520.0058046927555,
  cx=320.0, cy=240.0 (image-center principal point, v1 assumption).
  home_lat=-35.363262 home_lon=149.165237 home_alt_m=584.0 (config/field_polygon.json).
  mount offset (body frame) = (0, 0, -0.08) m (config/ndvi_camera.json mount.mount_pose_xyz_rpy).
  camera<->body axis signs = (+1, -1, -1) (ADR-007 nadir extrinsic quat_wxyz=(0,1,0,0): "camera
  X=body+X, Y=body-Y, Z=body-Z").
"""
