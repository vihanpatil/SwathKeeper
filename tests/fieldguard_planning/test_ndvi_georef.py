class TestInverseTransformRoundTrip(unittest.TestCase):
    """world_enu_to_pixel must be the true inverse of pixel_to_ground_enu (composed with the
    lat/lon step) -- complements the independent hand fixtures above, which validate the FORWARD
    direction is correct; this validates the inverse (used by NdviHeatmapGrid) agrees with it."""

    def test_round_trip_several_poses_and_pixels(self):
        cases = [
            ((0.0, 0.0, 15.0), IDENTITY_Q, 320.0, 240.0),
            ((0.0, 0.0, 15.0), IDENTITY_Q, 580.0029, 240.0),
            ((100.0, 50.0, 20.0), yaw_quat(math.radians(90.0)), 632.0035, 83.9983),
            ((30.0, 40.0, 18.0), yaw_quat(math.radians(-53.0)), 200.0, 350.0),
        ]
        for drone_pos, q, u, v in cases:
            ground = pixel_to_ground_enu(u, v, INTR, drone_pos, q)
            self.assertIsNotNone(ground)
            u2, v2 = world_enu_to_pixel((ground[0], ground[1], 0.0), drone_pos, q, INTR)
            self.assertAlmostEqual(u2, u, places=4, msg=f"pixel round-trip failed for {drone_pos},{q}")
            self.assertAlmostEqual(v2, v, places=4, msg=f"pixel round-trip failed for {drone_pos},{q}")

    def test_round_trip_combined_yaw_pitch_poses(self):
        """Round-trips at TILTED poses -- the cases above are identity/yaw-only, so they never
        exercise the pitch half of the rotation in the inverse direction. If forward and inverse
        disagreed under tilt, NdviHeatmapGrid would sample pixels from a different footprint than
        pixel_to_ground_enu claims to cover, exactly when the drone is translating (i.e. always)."""
        q_90_10 = yaw_pitch_quat(math.radians(90.0), math.radians(10.0))
        cases = [
            ((50.0, -30.0, 20.0), q_90_10, 320.0, 240.0),        # fixture 5's pose, center pixel
            ((50.0, -30.0, 20.0), q_90_10, 632.0035, 83.9983),   # same pose, off-nadir both axes
            ((0.0, 0.0, 20.0), pitch_quat(math.radians(10.0)), 100.0, 400.0),  # pure pitch
            ((30.0, 40.0, 18.0), yaw_pitch_quat(math.radians(-53.0), math.radians(-7.0)),
             200.0, 350.0),                                       # negative yaw AND nose-up pitch
        ]
        for drone_pos, q, u, v in cases:
            ground = pixel_to_ground_enu(u, v, INTR, drone_pos, q)
            self.assertIsNotNone(ground)
            u2, v2 = world_enu_to_pixel((ground[0], ground[1], 0.0), drone_pos, q, INTR)
            self.assertAlmostEqual(u2, u, places=4, msg=f"pixel round-trip failed for {drone_pos},{q}")
            self.assertAlmostEqual(v2, v, places=4, msg=f"pixel round-trip failed for {drone_pos},{q}")

    def test_round_trip_through_latlon_combined_yaw_pitch(self):
        """Same end-to-end loop as test_round_trip_through_latlon_and_back (pixel -> lat/lon ->
        mission-side latlon_to_enu -> pixel), but at a tilted pose: the geodetic seam must also
        hold when the pitch half of the rotation is live, not just under yaw."""
        drone_pos = (50.0, -30.0, 20.0)
        q = yaw_pitch_quat(math.radians(90.0), math.radians(10.0))
        u, v = 500.0, 120.0
        lat, lon = pixel_to_latlon(u, v, INTR, drone_pos, q, HOME_LAT, HOME_LON, HOME_ALT)
        e, n = latlon_to_enu(lat, lon, HOME_LAT, HOME_LON)
        u2, v2 = world_enu_to_pixel((e, n, 0.0), drone_pos, q, INTR)
        self.assertAlmostEqual(u2, u, places=3)
        self.assertAlmostEqual(v2, v, places=3)

    def test_round_trip_through_latlon_and_back(self):
        """Full loop: pixel -> lat/lon -> ENU (mission_waypoints.latlon_to_enu, the mission-side
        transform) -> pixel (world_enu_to_pixel). Confirms the georef stitch and the mission
        planner's ENU<->geodetic math agree end to end, not just within ndvi_georef.py."""
        drone_pos = (100.0, 50.0, 20.0)
        q = yaw_quat(math.radians(90.0))
        u, v = 632.0035, 83.9983
        lat, lon = pixel_to_latlon(u, v, INTR, drone_pos, q, HOME_LAT, HOME_LON, HOME_ALT)
        e, n = latlon_to_enu(lat, lon, HOME_LAT, HOME_LON)
        u2, v2 = world_enu_to_pixel((e, n, 0.0), drone_pos, q, INTR)
        self.assertAlmostEqual(u2, u, places=3)
        self.assertAlmostEqual(v2, v, places=3)


class TestNdviHeatmapGrid(unittest.TestCase):
    def _flat_grid_image(self, value: float, h=480, w=640):
        return [[value for _ in range(w)] for _ in range(h)]

    def test_single_frame_nadir_updates_center_cells(self):
        cells = [
            CoverageCell(cell_id="c_home", i=0, j=0, cx_m=0.0, cy_m=0.0),   # under the nadir camera
            CoverageCell(cell_id="c_far", i=1, j=0, cx_m=500.0, cy_m=500.0),  # far outside the FOV
        ]
        grid = NdviHeatmapGrid(cells, INTR)
        image = self._flat_grid_image(0.5)
        n_updated = grid.accumulate_frame(image, (0.0, 0.0, 15.0), IDENTITY_Q)
        self.assertEqual(n_updated, 1)
        means = grid.mean_grid()
        self.assertAlmostEqual(means["c_home"], 0.5, places=6)
        self.assertIsNone(means["c_far"])  # never imaged -- explicit None, not silently dropped
        self.assertEqual(grid.sample_counts()["c_home"], 1)
        self.assertEqual(grid.sample_counts()["c_far"], 0)
        self.assertEqual(grid.frames_accumulated, 1)

    def test_running_mean_across_two_frames(self):
        cells = [CoverageCell(cell_id="c_home", i=0, j=0, cx_m=0.0, cy_m=0.0)]
        grid = NdviHeatmapGrid(cells, INTR)
        grid.accumulate_frame(self._flat_grid_image(0.4), (0.0, 0.0, 15.0), IDENTITY_Q)
        grid.accumulate_frame(self._flat_grid_image(0.6), (0.0, 0.0, 15.0), IDENTITY_Q)
        means = grid.mean_grid()
        self.assertAlmostEqual(means["c_home"], 0.5, places=6)
        self.assertEqual(grid.sample_counts()["c_home"], 2)
        self.assertEqual(grid.frames_accumulated, 2)


