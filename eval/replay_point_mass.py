def verdicts(flights: Sequence[dict], trip: Optional[dict], bar: float) -> dict:
    q1_rows, mode_conflicts = [], []
    for f in flights:
        by_axis: Dict[str, list] = {}
        for fit in f["plant_fit"]:
            by_axis.setdefault(fit["timing_axis"], []).append(fit)
        # THE TWO-MODE CONTRADICTION, surfaced rather than hidden behind the primary mode
        # (QA finding C2). On the 2026-08-25 window the two command modes return OPPOSITE
        # argmins off identical telemetry; that disagreement IS the evidence that the window
        # decides nothing, and it belongs in the verdict rather than in whichever mode was
        # printed with a star.
        for label, fits in by_axis.items():
            winners = {fit["command_mode"]: fit["nearest_hypothesis"] for fit in fits}
            if len(set(winners.values())) > 1:
                thin = [fit for fit in fits
                        if fit["discriminating_power"] != "DISCRIMINATING"]
                mode_conflicts.append({
                    "stem": f["stem"], "timing_axis": label, "nearest_by_mode": winners,
                    "separation_quanta": {fit["command_mode"]:
                                          fit["hypothesis_separation_quanta"] for fit in fits},
                    "informative": not thin,
                    "reading": (
                        "REAL: both modes discriminate, so the disagreement is the receding "
                        "setpoint doing the work -- the latched schedule and the schedule actually "
                        "sent are different commands and a compliant plant answers them "
                        "differently" if not thin else
                        "NOISE: at least one mode is below the discrimination floor, so the "
                        "opposite argmins are two coin flips off the same telemetry -- this IS "
                        "what 'cannot tell' looks like")})
        for fit in f["plant_fit"]:
            if fit["command_mode"] != CMD_PRIMARY:
                continue        # the primary mode selects the hypothesis; see the CMD_* comment
            q1_rows.append({"stem": f["stem"], "timing_axis": fit["timing_axis"],
                            "timing_kind": fit["timing_kind"],
                            "admissible": fit["timing_admissible"],
                            "implied_cruise_speed_mps": fit["timing_implied_cruise_speed_mps"],
                            "observed_along_cmd_m": fit["observed_along_cmd_window_m"],
                            "observed_cross_track_m": fit["observed_cross_track_m"],
                            "along_cmd_decomposition_m": fit["along_cmd_decomposition_m"],
                            "nearest_hypothesis": fit["nearest_hypothesis"],
                            "command_path_worked": fit["command_path_worked"],
                            "hypotheses_m": fit["hypotheses_along_cmd_m"],
                            "discriminating_power": fit["discriminating_power"],
                            "hypothesis_separation_m": fit["hypothesis_separation_m"],
                            "hypothesis_separation_quanta":
                                fit["hypothesis_separation_quanta"],
                            "best_plant_by_rms": fit["best_plant_by_rms"],
                            "best_rms_m": fit["best_rms_m"],
                            "best_rms_frac_of_path": fit["best_rms_frac_of_path"],
                            "rms_shape_verdict": fit["rms_shape_verdict"],
                            "fit_verdict": fit["fit_verdict"],
                            "fitted_a_max_ne_mps2": fit["fitted_a_max_ne_mps2"]})
    # EVERY AGGREGATE BELOW IS OVER ADMISSIBLE ROWS ONLY (QA finding G77). An inadmissible axis
    # describes a flight the plant could not have flown, so a verdict read off it is a verdict about
    # arithmetic. The rows themselves stay in `rows`, flagged, because hiding the spread an
    # assumption is responsible for is the opposite of the point.
    adm_rows = [r for r in q1_rows if r["admissible"]]
    # A fitted accel limit is only meaningful where the plant model actually reproduces the window
    # AND the window can discriminate AND the axis is possible. Reading one off a NO-FIT window
    # (2026-08-18 returns the grid's floor, 0.05 m/s^2), off an unanswerable one, or off an
    # inadmissible axis puts a number on a flight that has none -- the last of those was the sole
    # source of the published 1.85 endpoint.
    fitted = [r["fitted_a_max_ne_mps2"] for r in adm_rows
              if r["fitted_a_max_ne_mps2"] is not None and r["fit_verdict"].startswith("FIT")]
    fitted_from = [f"{r['stem']} / {r['timing_axis']}" for r in adm_rows
                   if r["fitted_a_max_ne_mps2"] is not None and r["fit_verdict"].startswith("FIT")]
    excluded = [{"stem": r["stem"], "timing_axis": r["timing_axis"],
                 "implied_cruise_speed_mps": r["implied_cruise_speed_mps"],
                 "fit_verdict": r["fit_verdict"],
                 "fitted_a_max_ne_mps2": r["fitted_a_max_ne_mps2"]}
                for r in q1_rows if not r["admissible"]]
    worked: Dict[str, object] = {}
    for r in adm_rows:
        val = UNANSWERABLE if r["command_path_worked"] is None else r["command_path_worked"]
        prev = worked.get(r["stem"], val)
        worked[r["stem"]] = val if prev == val else "MIXED"
    counts = {"true": sum(1 for v in worked.values() if v is True),
              "false": sum(1 for v in worked.values() if v is False),
              UNANSWERABLE.lower(): sum(1 for v in worked.values() if v == UNANSWERABLE),
              "mixed": sum(1 for v in worked.values() if v == "MIXED")}
    moved = sorted(k for k, v in worked.items() if v is True)
    not_moved = sorted(k for k, v in worked.items() if v is False)
    cannot = sorted(k for k, v in worked.items() if v in (UNANSWERABLE, "MIXED"))
    parts = []
    if moved:
        parts.append(f"the command path demonstrably MOVED the aircraft on {', '.join(moved)}")
    if not_moved:
        parts.append(f"demonstrably did NOT on {', '.join(not_moved)}")
    if cannot:
        parts.append(f"and {', '.join(cannot)} CANNOT TELL -- the window is too short to separate "
                     f"the hypotheses above the telemetry quantum")
    q1 = {
        "question": "Does a default-parameter point mass reproduce the observed displacements?",
        "command_mode": CMD_PRIMARY,
        # The one sentence Q1 may be quoted as.
        "headline": ("; ".join(parts) + "." if parts else "no window could be scored."),
        "rows": q1_rows,
        "aggregates_over": "admissible rows only",
        "n_rows_total_admissible": [len(q1_rows), len(adm_rows)],
        "inadmissible_rows_excluded_from_aggregates": excluded,
        "nearest_hypothesis_counts": {
            h: sum(1 for r in adm_rows if r["nearest_hypothesis"] == h)
            for h in ("H_broken_m", "H_plant_m", "H_compliant_m")},
        "nearest_hypothesis_is_only_meaningful_when": (
            "discriminating_power == DISCRIMINATING; the counts above include rows where it is "
            "not, and those rows contribute UNANSWERABLE to every verdict that matters"),
        "fit_verdict_counts": {v: sum(1 for r in adm_rows if r["fit_verdict"].startswith(v))
                               for v in ("FIT", "PARTIAL", "NO-FIT", "EVIDENCE THIN",
                                         "EVIDENCE INSUFFICIENT")},
        "command_path_worked_by_flight": {k: (v if v is not True and v is not False else v)
                                          for k, v in worked.items()},
        "command_path_worked_counts_by_flight": counts,
        "two_command_mode_conflicts": mode_conflicts,
        "fitted_a_max_ne_mps2_range": [min(fitted), max(fitted)] if fitted else None,
        "fitted_a_max_sources": fitted_from,
        "fitted_a_max_from": (f"FIT windows on ADMISSIBLE axes only (discriminating + rms within "
                              f"10 % of path + a tick period the plant's velocity cap allows): "
                              f"{fitted_from or 'none'}. See transfer_gap_register TG-5 for why "
                              f"this is ESTIMATED, not MEASURED."),
        "wpnav_acc_default_mps2": GUIDED_DEFAULT.a_max_ne_mps2,
        "timing_robustness": {f["stem"]: {
            "best_admissible_rms_frac_of_path":
                f["timing_robustness"]["best_admissible"]["best_rms_frac_of_path"],
            "at_dt_s": f["timing_robustness"]["best_admissible"]["dt_s"],
            "at_entry_window_s": f["timing_robustness"]["best_admissible"]["entry_window_s"],
            "admissible_dt_floor_s": f["timing_robustness"]["admissible_dt_floor_s"],
            "best_verdict_over_admissible":
                f["timing_robustness"]["best_verdict_over_admissible"],
            "any_admissible_cell_fits": f["timing_robustness"]["any_admissible_cell_fits"]}
            for f in flights
            if f.get("timing_robustness") and f["timing_robustness"]["best_admissible"]},
        "poscontrol_bare_ruled_out_by": (
            "every window whose entry speed exceeds POSCONTROL_SPEED_MS (5.0 m/s): the rival "
            "hypothesis forbids a speed the vehicle demonstrably held, so the traced "
            "pva_control_start seeding from WPNAV_SPD 10 m/s is confirmed by the flown data, not "
            "only by reading the source."),
    }

    q2_rows = []
    for f in flights:
        for cf in f["counterfactual"]:
            s = cf["summary"]
            q2_rows.append({"stem": f["stem"], "timing_axis": cf["timing_axis"],
                            "flown_gt_cpa_m": cf["flown_gt_cpa_m"],
                            "horizon_after_takeover_s": cf["horizon_after_takeover_s"],
                            "all_cells_cover_flown_cpa": cf["all_cells_cover_flown_cpa"],
                            "any_resolved_physically": s["any_resolved_physically"],
                            "min_physically_resolving_lead_s":
                                s["min_physically_resolving_lead_s"],
                            "min_legally_resolving_lead_s": s["min_legally_resolving_lead_s"],
                            "min_physically_resolving_lead_by_plant_s":
                                s["min_physically_resolving_lead_by_plant_s"],
                            "min_legally_resolving_lead_by_plant_s":
                                s["min_legally_resolving_lead_by_plant_s"],
                            "n_physically_resolving_but_illegal":
                                s["n_physically_resolving_but_illegal"],
                            "n_deferrals": s["n_deferrals"],
                            "n_band_exits": s["n_band_exits"],
                            "resolving_candidates_physically": sorted(
                                k for k, v in s["per_candidate"].items()
                                if v["ever_resolved_physically"])})
    q2 = {"question": (f"At what lead / candidate / plant would the flown bird have been cleared by "
                       f">= {bar:.2f} m IN BAND and actually passed (resolved, not deferred and not "
                       f"a band exit)?"),
          "read_which_number": (
              "PHYSICAL for a sensor-horizon spec -- it is a claim about the aircraft. LEGAL for "
              "what today's policy would have been allowed to command. The gap between them is the "
              "XY-only swept-path tree vet on a lane the vehicle overflies at 15 m, not a limit of "
              "the airframe."),
          "band_exit_rule": (
              "a cell whose vertical separation leaves +/-vertical_threat_m during the horizon is "
              "BAND-EXIT: its gt_cpa is the last IN-BAND instant, not the separation at the "
              "crossing, so it is neither cleared nor resolved and `min_horizontal_threat_m` is "
              "printed instead (ADR-013 am. 18's pre-registered vacuous green)"),
          "rows": q2_rows}

    q3 = None
    if trip:
        q3 = {
            "question": "At the maximum lead nadir geometry can give, can ANY escape clear the bar?",
            "sensor_horizon_m": trip["sensor_horizon"]["along_track_m"],
            "bar_m": bar,
            "safe_speed_exists_in_2_10_mps": trip["safe_speed_exists_in_2_10"],
            "speed_at_which_nadir_becomes_safe_mps": trip["max_safe_speed_mps"],
            "safe_speed_band_mps": trip["safe_speed_band_mps"],
            "why_no_safe_speed": trip["why_no_safe_speed"],
            "cleared_at_hover_limit": trip["hover_limit"]["cleared_by_any_plant"],
            "tripwire_fires": not (trip["safe_speed_exists_in_2_10"]
                                   or trip["hover_limit"]["cleared_by_any_plant"]),
            "required_sensor_horizon_m_at_flown_speed": None,
        }
        flown = trip.get("measured_from", {}).get("flown_speed_mps")
        if flown is not None:
            nearest = min(trip["speed_sweep"], key=lambda r: abs(r["mission_speed_mps"] - flown))
            q3["required_sensor_horizon_m_at_flown_speed"] = {
                "mission_speed_mps": nearest["mission_speed_mps"],
                **{k: v["required_sensor_horizon_m"] for k, v in nearest["plants"].items()}}
    return {"q1": q1, "q2": q2, "q3": q3}


