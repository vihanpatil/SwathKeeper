#!/usr/bin/env python3
"""THE OFFLINE CONFOUND-RESOLVER: replay the three committed live flights through a point-mass
plant and separate candidate ordering, warning time, and plant compliance (ADR-016, Council
Ruling 001; ADR-017 for what the speed sweep now decides).

WHY IT LIVES IN eval/ AND NOT scripts/. `scripts/` holds CHECKERS AND GATES -- tools with a
pass/fail contract that CI runs on every push (`check_live_flight_log.py`, `check_mission_geofence.py`).
This is a STUDY: it answers three open questions once, writes an artifact, and has no bar to
enforce. It must never be wired into CI as a gate, because a study whose numbers move when the
sweep grid changes would be a gate that fails for reasons unrelated to the aircraft. Its OUTPUT can
seed a gate later (a required-lead-time bar beside CPA is the obvious one); the study itself is
evidence, not enforcement. Same reasoning that puts `eval/annotate_real_clip.py` in eval/.

THE THREE QUESTIONS, and how each is answered:

  Q1 PLANT FIT -- does an accel/jerk/velocity-limited point mass at ArduCopter's real GUIDED
     defaults reproduce the displacement actually observed inside each GUIDED window? The model is
     driven by the SAME setpoint schedule the executor really sent, from the vehicle's real entry
     state, over the real window. Three rival hypotheses are scored against the one observation:
       H_broken     -- the command did nothing; the vehicle coasted on its cruise velocity;
       H_plant      -- a default-limited point mass;
       H_compliant  -- the vehicle reached the commanded setpoint.
     The one nearest the observation wins. If H_plant wins, "0.5-4 % compliance" is arithmetic, not
     a defect, and R4-as-candidate-ordering is not what is broken.

  Q2 COUNTERFACTUAL SWEEP -- lead time x candidate (the policy's own seven headings, plus a pure
     climb, a speed-brake, and a forward sidestep that does not demand deceleration) x plant limits
     (as-flown defaults, the rival PosControl-bare defaults, and the ANGLE_MAX physical ceiling).
     For each cell: would the encounter's real bird have been cleared by >= min_bird_clearance_m?

  Q3 THE TRIPWIRE / THE SPEED DOCTRINE -- nadir geometry bounds lead time at
     (half-footprint at the bird's depth) / (closing speed). ADR-017 keeps the camera nadir and buys
     warning time by SLOWING DOWN instead, and the re-fly's encounter-lane speed is read off the
     speed sweep here. So the sweep over mission speeds is this file's load-bearing output, and
     "no speed clears the bar" is reported as itself -- never interpolated into a reassuring number.

WHAT IT REUSES RATHER THAN RE-IMPLEMENTS -- a second parser is a second chance to lie:
  * `scripts/check_live_flight_log.py` for the flight-log path extraction, the truth-track loader
    and its reviewed TRUTH_BINDINGS join, `pose_windows`, and above all `ground_truth_cpa` -- every
    counterfactual CPA in this file is scored by the exact function that produced the flown
    verdict, on a synthetic `flown_path_enu` + `tick_stamp_sim_s` pair;
  * `fieldguard_planning.avoidance_policy` for PolicyParams (the 3.00 m bar, the 10 m divert
    distance, the threat cylinder) and for `_CANDIDATE_ANGLES_DEG`/`_rotate`/`_unit` so the
    counterfactual headings are generated by the same geometry the policy uses;
  * `fieldguard_planning.geofence` so a counterfactual that would have hit a tree is reported as
    such instead of being counted as an escape;
  * `eval/point_mass.py` for the plant, whose constants all carry an ArduPilot source URL at the
    pinned SHA.

TIMING HONESTY. Only the 2026-08-25 log (schema 2) carries `run.tick_stamp_sim_s`, an absolute
Gazebo sim-time axis. The two historical logs have no time axis at all: their ticks are bare
integers. Every schema-1 result below is therefore produced TWICE, under the nominal 0.2 s
executor period (`CONTROL_HZ` 5.0) and under the 0.16 s median actually measured on the one flight
that recorded time, and both are reported. Nothing from a schema-1 log is ever labelled "measured".

Usage:
    python3 eval/replay_point_mass.py                      # all committed live flight logs
    python3 eval/replay_point_mass.py --logs <path> ...    # specific logs
    python3 eval/replay_point_mass.py --json-only          # artifact, no stdout report
"""
