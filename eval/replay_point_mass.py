# =============================================================================== bird ground truth
class StaticBirdTruth:
    """A `TruthTrack`-shaped view of a DEMO bird, so the two historical flights can be scored by
    `check_live_flight_log.ground_truth_cpa` -- the same two-pass CPA the real take is scored by.

    The 2026-08-18 and 2026-08-23 encounters were driven by the demo/virtual bird: every detection
    event on both flights carries the identical `position_enu` (30, 30, 15), i.e. the bird's
    position IS a constant this project chose, which is exactly the `DET_DEMO_VIRTUAL` case the gate
    documents as "the logged position IS exact truth". Wrapping it in the TruthTrack interface
    (span / timeline / birds / candidates_at) is cheaper AND safer than giving those flights their
    own CPA routine: the vertical scoping, the segment math and the pose-window pass all come along.

    `from_log` REFUSES a log whose detections disagree about where the bird was, rather than
    averaging them -- a moving demo bird would need the real TruthTrack, not this shim."""

    def __init__(self, bird_id: str, pos: Sequence[float], span: Tuple[float, float]):
        self.path = None
        self.bird_id = bird_id
        self.pos = (float(pos[0]), float(pos[1]), float(pos[2]))
        self.span = (float(span[0]), float(span[1]))
        self.timeline = {bird_id: [(self.span[0], self.span[1], self.pos, self.span[0])]}
        self.birds = {bird_id: {"bird_id": bird_id}}
        self.landed_counts = {bird_id: 1}
        self.unknown_bird_ids: List[str] = []
        self.unobserved_bird_ids: List[str] = []

    @classmethod
    def from_log(cls, log: dict, span: Tuple[float, float]) -> "StaticBirdTruth":
        dets = [ev for ev in (log.get("events") or [])
                if isinstance(ev, dict) and ev.get("kind") == "detection"
                and isinstance(ev.get("position_enu"), (list, tuple))]
        if not dets:
            raise ValueError("no detection events: this log carries no bird position at all")
        positions = {tuple(round(float(c), 6) for c in ev["position_enu"][:3]) for ev in dets}
        if len(positions) != 1:
            raise ValueError(f"demo-bird shim refuses a MOVING bird: {len(positions)} distinct "
                             f"detection positions in this log. Use a real applied-pose truth "
                             f"track (TRUTH_BINDINGS) instead of this static shim.")
        pos = positions.pop()
        track_id = str(dets[0].get("track_id") or dets[0].get("frame_id") or "demo_bird")
        return cls(track_id, pos, span)

    def candidates_at(self, t_sim_s: Optional[float]):
        if t_sim_s is None or t_sim_s < self.span[0] or t_sim_s > self.span[1]:
            return None
        return {self.bird_id: gate.BirdTruth([self.pos], False)}


# ==================================================================================== the encounter
@dataclass
class Encounter:
    """One flight's single bird encounter, with everything the replay needs and nothing else."""
    stem: str
    path: Path
    log: dict
    schema_version: Optional[int]
    flown_path: List[Optional[Tuple[float, float, float]]]
    measured_stamps: Optional[List[float]]
    takeover_tick: int
    resume_tick: int
    maneuvers: List[Tuple[int, Tuple[float, float, float]]]
    params: dict
    truth_kind: str
    truth: object

    @property
    def n_maneuvers(self) -> int:
        return len(self.maneuvers)


def _pt(p) -> Optional[Tuple[float, float, float]]:
    try:
        return (float(p[0]), float(p[1]), float(p[2]))
    except (TypeError, ValueError, IndexError):
        return None


def load_encounter(path: Path) -> Tuple[Optional[Encounter], Optional[str]]:
    """(Encounter, None) or (None, reason). NEVER a bare None (QA finding M1, 2026-08-26).

    A silent skip here is the instrument going blind on exactly the failure it exists to watch for.
    A log with a `takeover` and no `resume` is a GUIDED LOCK -- the vehicle never handed back --
    which is a plausible outcome of the threat-hysteresis change ADR-016 bundles, and the first
    version of this function returned None for it and let `build_report` walk on. The run then
    exited 0 with an empty table and named the skipped log NOWHERE.

    Deliberately strict about WHICH log: the three committed flights each contain exactly one
    encounter, but nothing here assumes that -- a log with several raises rather than silently
    replaying the first."""
    log = json.loads(Path(path).read_text())
    events = log.get("events") or []
    takeovers = [ev for ev in events if ev.get("kind") == "takeover"]
    resumes = [ev for ev in events if ev.get("kind") == "resume"]
    if not takeovers and not resumes:
        return None, ("no takeover and no resume event: this log records no GUIDED encounter at "
                      "all (a flight with avoidance armed and nothing to avoid, or a log written "
                      "before the encounter)")
    if not resumes:
        return None, (f"{len(takeovers)} takeover(s) but NO resume: the vehicle never handed back "
                      f"to AUTO. That is a GUIDED LOCK, not an absence of evidence -- investigate "
                      f"the flight before replaying anything else")
    if not takeovers:
        return None, (f"{len(resumes)} resume(s) but NO takeover: the log is truncated or the "
                      f"encounter began before recording started")
    if len(takeovers) > 1 or len(resumes) > 1:
        raise ValueError(f"{Path(path).name}: {len(takeovers)} takeovers / {len(resumes)} resumes. "
                         f"This replay models ONE encounter per flight (which is what the three "
                         f"committed logs contain); extend it deliberately, do not replay the first "
                         f"and drop the rest.")
    takeover_tick, resume_tick = int(takeovers[0]["tick"]), int(resumes[0]["tick"])
    flown = [_pt(p) for p in (log.get("flown_path_enu") or [])]
    run = log.get("run") if isinstance(log.get("run"), dict) else None
    schema = gate.schema_version(log)
    stamps = None
    if run:
        raw = run.get("tick_stamp_sim_s") or []
        stamps = [gate._num(x) for x in raw]
        if any(s is None for s in stamps):
            stamps = None

    maneuvers: List[Tuple[int, Tuple[float, float, float]]] = []
    params: dict = {}
    for ev in events:
        if ev.get("kind") != "maneuver":
            continue
        sp = _pt(ev.get("setpoint_enu"))
        if sp is None:
            continue
        maneuvers.append((int(ev["tick"]), sp))
        dbg = ev.get("debug")
        if isinstance(dbg, dict) and isinstance(dbg.get("params"), dict) and not params:
            params = dict(dbg["params"])
    if run and isinstance(run.get("policy_params"), dict):
        params = dict(run["policy_params"])
    if not maneuvers:
        return None, ("a takeover/resume pair with NO maneuver event carrying a setpoint_enu: the "
                      "loop took GUIDED authority and commanded nothing, or every setpoint was "
                      "malformed. Either way there is no command to replay")
    maneuvers.sort()

    return Encounter(stem=Path(path).stem, path=Path(path), log=log, schema_version=schema,
                     flown_path=flown, measured_stamps=stamps, takeover_tick=takeover_tick,
                     resume_tick=resume_tick, maneuvers=maneuvers, params=params,
                     truth_kind="", truth=None), None


def p99_step_m(enc: Encounter) -> float:
    """The flight's 99th-percentile distance per tick -- its cruise legs. p50 is 0 on every flight
    (`/ap/pose/filtered` updates slower than the 5 Hz tick, so the path is a staircase), which is
    why the high percentile is the one that carries the cruise speed."""
    steps = sorted(math.dist(a[:2], b[:2]) for a, b in zip(enc.flown_path, enc.flown_path[1:])
                   if a is not None and b is not None)
    return steps[min(len(steps) - 1, int(0.99 * len(steps)))] if steps else 0.0


def axis_admissible(enc: Encounter, kind: str, dt_s: Optional[float]) -> Tuple[bool, Optional[float]]:
    """(is this time axis physically possible for this flight, implied cruise speed).

    A MEASURED axis is always admissible: it is an observation, and a heuristic does not get to
    overrule one. An ASSUMED axis implies a cruise speed of `p99 step / dt`, and if that exceeds the
    plant's own velocity cap the axis describes a flight this aircraft could not have flown.

    CALIBRATED, not guessed: the one flight with a real clock (2026-08-25) scores 1.01x on this
    heuristic -- p99 1.616 m over a 0.16 s median tick = 10.099 m/s against WPNAV_SPD 10 -- so the
    test sits essentially exactly on a true axis, and 2026-08-23's assumed 0.16 s axis at 12.312 m/s
    (1.23x) is a solid exclusion rather than a borderline one.

    WHY IT HAS TO REACH THE DECLARED AXES and not only the robustness probe (QA finding G77,
    2026-08-26): that inadmissible 0.16 s axis carried a FIT verdict into `verdict.q1.rows`, was
    counted in `fit_verdict_counts`, and was the SOLE source of the 1.85 endpoint of the published
    `fitted_a_max_ne_mps2_range` -- the number TG-5 publishes and an R4 sizing would quote off a
    time axis the vehicle could not have flown."""
    if kind == "measured":
        return True, None
    if not dt_s:
        return True, None
    implied = p99_step_m(enc) / dt_s
    return bool(implied <= GUIDED_DEFAULT.v_max_ne_mps + 1e-9), implied


def timing_axes(enc: Encounter) -> List[dict]:
    """The time axis (or axes) this flight may be replayed on.

    Schema 2: ONE axis, MEASURED, straight out of `run.tick_stamp_sim_s`.
    Schema 1: TWO axes, both ASSUMED -- the nominal executor period and the only sim-seconds-per-tick
    this project has ever measured. Both are reported; neither is ever called measured. This is not
    pedantry: at 0.20 s/tick the 2026-08-23 window is 3.8 s long and at 0.16 s it is 3.0 s, and the
    deceleration you infer from it moves by 50 %.

    Each axis carries its own `admissible` flag (see `axis_admissible`). An inadmissible axis is
    still REPLAYED and still PRINTED -- suppressing it would hide the spread the assumption is
    responsible for -- but it is excluded from every aggregate."""
    n = len(enc.flown_path)
    if enc.measured_stamps and len(enc.measured_stamps) >= n:
        return [{"label": "measured", "kind": "measured", "admissible": True,
                 "implied_cruise_speed_mps": None,
                 "times": [float(s) for s in enc.measured_stamps[:n]],
                 "source": "run.tick_stamp_sim_s (absolute Gazebo sim seconds, gz_clock_stream)"}]
    out = []
    for dt_s, source in ((NOMINAL_TICK_S,
                          f"ASSUMED: nominal executor period 1/CONTROL_HZ = {NOMINAL_TICK_S:.2f} s "
                          f"(fieldguard_planning.avoidance_node.CONTROL_HZ)"),
                         (_measured_median_tick_s(),
                          "ASSUMED: median sim-seconds-per-tick measured on the 2026-08-25 take, "
                          "the only flight with a recorded time axis")):
        ok, implied = axis_admissible(enc, "assumed", dt_s)
        out.append({"label": f"assumed_dt_{dt_s:.2f}s", "kind": "assumed", "dt_s": dt_s,
                    "admissible": ok,
                    "implied_cruise_speed_mps": round(implied, 3) if implied else None,
                    "times": [i * dt_s for i in range(n)], "source": source})
    return out


_MEASURED_MEDIAN_CACHE: Optional[float] = None


def _measured_median_tick_s() -> float:
    """Median tick period from whichever committed log actually recorded a time axis. Computed, not
    typed: the 0.16 s constant is an OBSERVATION of one flight and must move if that flight's
    artifact does."""
    global _MEASURED_MEDIAN_CACHE
    if _MEASURED_MEDIAN_CACHE is not None:
        return _MEASURED_MEDIAN_CACHE
    best: Optional[float] = None
    for p in sorted(RESULTS_DIR.glob("live_flight_log_*.json")):
        try:
            log = json.loads(p.read_text())
        except (OSError, json.JSONDecodeError, UnicodeDecodeError):
            continue
        run = log.get("run")
        if not isinstance(run, dict):
            continue
        stamps = [gate._num(x) for x in (run.get("tick_stamp_sim_s") or [])]
        deltas = sorted(b - a for a, b in zip(stamps, stamps[1:])
                        if a is not None and b is not None and b > a)
        if deltas:
            best = deltas[len(deltas) // 2]
    _MEASURED_MEDIAN_CACHE = round(best, 4) if best else MEASURED_TICK_S_FALLBACK
    return _MEASURED_MEDIAN_CACHE


def step_diagnostic(enc: Encounter, axes: Sequence[dict]) -> dict:
    """Is a schema-1 flight's ASSUMED tick period even plausible? Reported, never used to correct.

    The only handle a log with no clock leaves is its own step-size distribution: distance flown per
    tick. Divide the flight's p99 step (its cruise legs -- p50 is 0 on every flight, because
    `/ap/pose/filtered` updates slower than the 5 Hz tick and the path is a staircase) by an assumed
    tick period and you get the cruise speed that assumption implies. Compare it to the ONE cruise
    speed this project has measured on a clock, and a wrong assumption becomes visible instead of
    silently scaling every derived acceleration."""
    steps = [math.dist(a[:2], b[:2]) for a, b in zip(enc.flown_path, enc.flown_path[1:])
             if a is not None and b is not None]
    if not steps:
        return {}
    order = sorted(steps)
    p99 = order[min(len(order) - 1, int(0.99 * len(order)))]
    out = {"n_steps": len(steps), "p99_step_m": round(p99, 4), "max_step_m": round(max(steps), 4),
           "zero_steps_frac": round(sum(1 for s in steps if s <= 1e-9) / len(steps), 4),
           "implied_cruise_speed_mps": {}}
    for a in axes:
        dt = a.get("dt_s")
        if dt is None:
            times = a["times"]
            deltas = sorted(b - x for x, b in zip(times, times[1:]) if b > x)
            dt = deltas[len(deltas) // 2] if deltas else None
        if dt:
            out["implied_cruise_speed_mps"][a["label"]] = round(p99 / dt, 3)
    return out


def attach_truth(enc: Encounter, times: Sequence[float]) -> None:
    """Bind this flight to its bird ground truth, by the SAME route the safety gate uses.

    Schema 2 goes through `gate.resolve_truth`, which consults the reviewed `TRUTH_BINDINGS` pin
    first -- so this study joins the 2026-08-25 take to exactly the applied-pose log the gate's own
    breach verdict was measured against, and cannot silently pick a different one.
    Schema 1 gets the static demo-bird shim, because that is what those flights actually flew."""
    run = enc.log.get("run")
    if isinstance(run, dict):
        truth, problems = gate.resolve_truth(enc.path, run)
        if truth is None:
            raise ValueError(f"{enc.stem}: cannot resolve bird ground truth: {problems}")
        enc.truth, enc.truth_kind = truth, "applied_pose_truth_track"
        return
    span = (min(times) - 60.0, max(times) + 60.0)
    enc.truth = StaticBirdTruth.from_log(enc.log, span)
    enc.truth_kind = "demo_virtual_static"


# ==================================================================================== path helpers
def sample_at(times: Sequence[float], path: Sequence[Optional[Tuple[float, float, float]]],
              t: float) -> Optional[Tuple[float, float, float]]:
    """Linear interpolation of the flown polyline at absolute time `t`. The polyline IS the vehicle's
    telemetry, so interpolating between vertices makes exactly the constant-velocity-between-samples
    assumption `check_live_flight_log._lerp3` already makes -- no new modelling."""
    pts = [(times[i], path[i]) for i in range(min(len(times), len(path))) if path[i] is not None]
    if not pts:
        return None
    if t <= pts[0][0]:
        return pts[0][1]
    if t >= pts[-1][0]:
        return pts[-1][1]
    for (ta, a), (tb, b) in zip(pts, pts[1:]):
        if ta <= t <= tb:
            s = 0.0 if tb == ta else (t - ta) / (tb - ta)
            return gate._lerp3(a, b, s)
    return pts[-1][1]


def velocity_at(times: Sequence[float], path: Sequence[Optional[Tuple[float, float, float]]],
                t: float, window_s: float = 0.6) -> Tuple[float, float, float]:
    """Least-squares velocity over the `window_s` of telemetry ENDING at `t`.

    Least squares over a window, not a two-point secant, and the reason is in the data: the flown
    x-coordinate is quantised at ~9 mm (the lat/lon round-trip), so a secant across one 0.12 s tick
    turns one quantisation step into a 0.08 m/s phantom. A fit over ~4-5 samples averages it out.
    Ending at `t` rather than centred on it, because the entry velocity of a maneuver must be the
    velocity the vehicle ARRIVED with -- not one contaminated by the maneuver itself."""
    lo = t - window_s
    pts = [(times[i], path[i]) for i in range(min(len(times), len(path)))
           if path[i] is not None and lo <= times[i] <= t]
    if len(pts) < 2:
        pts = [(times[i], path[i]) for i in range(min(len(times), len(path)))
               if path[i] is not None and times[i] <= t][-3:]
    if len(pts) < 2:
        return (0.0, 0.0, 0.0)
    n = float(len(pts))
    mt = sum(p[0] for p in pts) / n
    denom = sum((p[0] - mt) ** 2 for p in pts)
    if denom <= 0.0:
        return (0.0, 0.0, 0.0)
    out = []
    for axis in range(3):
        ma = sum(p[1][axis] for p in pts) / n
        out.append(sum((p[0] - mt) * (p[1][axis] - ma) for p in pts) / denom)
    return (out[0], out[1], out[2])


def cpa_of(samples: Sequence[Tuple[float, Tuple[float, float, float]]], truth,
           params: dict) -> dict:
    """CPA of a SIMULATED path against the bird, through the gate's own `ground_truth_cpa`.

    The simulated samples are handed over as a synthetic (`flown_path_enu`, `tick_stamp_sim_s`)
    pair, which is precisely the shape that function takes for a real flight -- so a counterfactual
    and a flown verdict are produced by one implementation of the geometry, the vertical scoping and
    the two-pass discretisation fix."""
    path = [list(p) for _t, p in samples]
    stamps = [t for t, _p in samples]
    return gate.ground_truth_cpa(path, stamps, truth,
                                 float(params.get("vertical_threat_m", 6.0)),
                                 float(params.get("threat_radius_m", 12.0)))


# ======================================================================== Q1: does the plant fit?
# TWO COMMAND MODES, and the distinction is not cosmetic -- it was forced by the data.
# `as_commanded` replays the historical setpoint schedule verbatim. But those setpoints are
# STATE-DEPENDENT: the policy places each one at `drone_xy + 10 m * away_unit`, recomputed from
# wherever the aircraft actually was that tick. On the 2026-08-18 flight (which predates the latch
# entirely -- 61 maneuvers, 0 latch events) the vehicle continued north, so every subsequent
# setpoint was re-placed 10 m south OF ITS NEW POSITION, i.e. the commanded point receded northward
# by 24 m over the window. Feeding that schedule to a plant that DOES obey produces a vehicle
# chasing its own target: physically meaningless, because those commands would never have been
# issued to a vehicle that moved.
# `latched_first` holds the FIRST vetted setpoint for the whole window. It is state-independent, it
# is what ADR-005/006's latch actually does (2026-08-23 and 2026-08-25 both latch), and it is the
# only mode in which "H_compliant = the vehicle reached the commanded point" is a defined claim.
# WHICH IS PRIMARY, and why: `as_commanded`. Q1 asks "does the plant explain what the aircraft
# DID?", and only the schedule that was really sent can answer that -- measured on the 2026-08-23
# window at 0.16 s/tick, an rms of 0.50 m against 21.80 m of travel (2.3 %) for `as_commanded`
# versus 1.10 m (5.0 %) for `latched_first`. `latched_first` is reported beside it because it is the
# schedule a LATCHED executor issues, and the gap between the two is the price of the receding
# setpoint. On a window too short to discriminate the two modes can return OPPOSITE argmins off the
# same telemetry (2026-08-25: H_plant vs H_broken, 5 mm apart) -- `verdict.q1.two_command_mode_
# conflicts` reports that rather than letting whichever mode carries the star decide.
CMD_AS_SENT, CMD_LATCHED = "as_commanded", "latched_first"
CMD_PRIMARY = CMD_AS_SENT


def _fit_errors(samples, enc: Encounter, times) -> List[float]:
    """Per-tick horizontal distance between the simulated and the flown position, over the window.
    The fit statistic that does not depend on choosing a projection axis."""
    by_t = {round(t, 6): p for t, p in samples}
    errs = []
    for tick in range(enc.takeover_tick, enc.resume_tick + 1):
        if tick - 1 >= len(times) or enc.flown_path[tick - 1] is None:
            continue
        key = round(times[tick - 1], 6)
        if key not in by_t:
            continue
        f, m = enc.flown_path[tick - 1], by_t[key]
        errs.append(math.hypot(f[0] - m[0], f[1] - m[1]))
    return errs


ENTRY_VELOCITY_WINDOWS_S = (0.3, 0.6, 1.0, 2.0)
DEFAULT_ENTRY_WINDOW_S = 0.6


def timing_robustness(enc: Encounter, axes: Sequence[dict]) -> Optional[dict]:
    """Could a different TICK PERIOD or a different ENTRY-VELOCITY WINDOW rescue a schema-1 window
    that no plant fits? Two nuisance parameters, swept together, because they interact.

    Without this, "NO-FIT under the two assumed tick periods" is a weak claim on a log with no
    clock -- a reader can always answer "you assumed the wrong period". Two refinements QA forced:

    ADMISSIBILITY (finding M4). The raw best used to be quoted at dt 0.05 s, which implies a cruise
    speed of p99_step / dt = 17.6 m/s on the 2026-08-18 log -- above WPNAV_SPD 10 m/s, i.e. a speed
    the vehicle could not have flown. A cell is ADMISSIBLE only if its implied cruise speed is
    within the plant's own velocity cap (dt >= 0.089 s here). Only admissible cells are quoted; the
    inadmissible ones stay in `rows` so the filter is auditable.

    ENTRY-VELOCITY WINDOW (finding M3). On a log that is 83 % zero steps, the 0.6 s least-squares
    window is measuring the staircase as much as the vehicle: the estimate runs 3.006 m/s at 0.3 s,
    0.902 at 0.6 and 1.252 at 2.0. Since the entry velocity sets H_broken outright, the window is
    swept too and the verdict is reported over the whole grid rather than at one arbitrary cell.

    Skipped for a flight carrying a measured axis, where there is nothing to assume."""
    if any(a["kind"] == "measured" for a in axes):
        return None
    n = len(enc.flown_path)
    steps = sorted(math.dist(a[:2], b[:2]) for a, b in zip(enc.flown_path, enc.flown_path[1:])
                   if a is not None and b is not None)
    p99 = steps[min(len(steps) - 1, int(0.99 * len(steps)))] if steps else 0.0
    v_cap = GUIDED_DEFAULT.v_max_ne_mps
    dt_floor = p99 / v_cap if v_cap > 0 else 0.0
    rows = []
    for dt in (0.05, 0.08, 0.10, 0.13, 0.16, 0.20, 0.25, 0.30, 0.40):
        implied = p99 / dt if dt > 0 else None
        admissible = bool(implied is not None and implied <= v_cap + 1e-9)
        axis = {"label": f"probe_dt_{dt:.2f}s", "kind": "assumed", "dt_s": dt,
                "times": [i * dt for i in range(n)], "source": "tick-period robustness probe"}
        for win in ENTRY_VELOCITY_WINDOWS_S:
            fit = plant_fit(enc, axis, CMD_PRIMARY, fit_a_max=False, entry_window_s=win)
            rows.append({"dt_s": dt, "entry_window_s": win,
                         "implied_cruise_speed_mps": round(implied, 3) if implied else None,
                         "admissible": admissible,
                         "entry_speed_mps": fit["entry_speed_mps"],
                         "best_plant": fit["best_plant_by_rms"], "best_rms_m": fit["best_rms_m"],
                         "best_rms_frac_of_path": fit["best_rms_frac_of_path"],
                         "rms_shape_verdict": fit["rms_shape_verdict"],
                         "nearest_hypothesis": fit["nearest_hypothesis"]})
    usable = [r for r in rows if r["best_rms_frac_of_path"] is not None]
    adm = [r for r in usable if r["admissible"]]
    best_adm = min(adm, key=lambda r: r["best_rms_frac_of_path"]) if adm else None
    best_raw = min(usable, key=lambda r: r["best_rms_frac_of_path"]) if usable else None
    return {"rows": rows,
            "p99_step_m": round(p99, 4),
            "admissible_dt_floor_s": round(dt_floor, 4),
            "admissibility_rule": (f"implied cruise = p99 step / dt must not exceed the plant's own "
                                   f"v_max_ne {v_cap:g} m/s -> dt >= {dt_floor:.4f} s"),
            "best_admissible": best_adm,
            "best_over_all_cells_including_inadmissible": best_raw,
            # The question is not "is the fit bad at every cell" but "is there ANY ADMISSIBLE cell
            # at which a default plant FITS" -- the 10 % threshold `plant_fit` itself uses. A sweep
            # that only reached PARTIAL has not rescued the flight.
            "any_admissible_cell_fits": bool(best_adm
                                             and best_adm["best_rms_frac_of_path"] <= 0.10),
            "best_verdict_over_admissible": (best_adm["rms_shape_verdict"].split(" --")[0]
                                             if best_adm else None),
            "note": ("the flown displacement is a fact independent of the time axis; only the "
                     "implied SPEED moves with it, so this sweep asks whether ANY plausible tick "
                     "period and entry-velocity window make a default-limited plant reproduce the "
                     "window. dt below 0.20 s is physically reachable for a 5 Hz WALL-clock timer "
                     "whenever the sim ran slower than real time, which is why the sweep goes down "
                     "to 0.05 s -- and why the admissibility filter is needed to throw the "
                     "impossible end of it away again.")}


def plant_fit(enc: Encounter, axis: dict, command_mode: str, fit_a_max: bool = True,
              entry_window_s: float = DEFAULT_ENTRY_WINDOW_S) -> dict:
    """Drive the point mass with the setpoints the executor really sent, and score three rival
    explanations of the observed displacement against the one observation."""
    times = axis["times"]
    t0 = times[enc.takeover_tick - 1]
    t_resume = times[enc.resume_tick - 1]
    p0 = enc.flown_path[enc.takeover_tick - 1]
    v0 = velocity_at(times, enc.flown_path, t0, window_s=entry_window_s)
    sent = [(times[tick - 1], sp) for tick, sp in enc.maneuvers if tick - 1 < len(times)]
    commands = [sent[0]] if command_mode == CMD_LATCHED else sent
    cmd_vec = (sent[0][1][0] - p0[0], sent[0][1][1] - p0[1])
    cmd_dist = math.hypot(*cmd_vec)
    cmd_unit = _unit(cmd_vec) or (0.0, 0.0)
    # "If GUIDED authority had continued" -- the model keeps flying the same command for SETTLE_S
    # past the resume. The real vehicle was back in AUTO by then, so this is explicitly a
    # counterfactual and never compared to the observed settled figure; it prices how much of the
    # shortfall is WINDOW LENGTH rather than plant.
    t_hold = t_resume + SETTLE_S
    tick_times = [times[i] for i in range(enc.takeover_tick - 1, min(enc.resume_tick, len(times)))]
    want = sorted(set(tick_times + [t_resume, t_hold]))

    def along(a, b) -> float:
        return (b[0] - a[0]) * cmd_unit[0] + (b[1] - a[1]) * cmd_unit[1]

    obs_window = along(p0, enc.flown_path[enc.resume_tick - 1])
    obs_settled = along(p0, sample_at(times, enc.flown_path, min(t_hold, times[-1])))

    # H_broken: no command took effect; the vehicle coasted on its entry velocity.
    ballistic_window = (v0[0] * cmd_unit[0] + v0[1] * cmd_unit[1]) * (t_resume - t0)

    # CRUISE LEAK -- the reason `observed_along_cmd` is not a dodge measurement (QA finding M6).
    # The projection onto the commanded direction decomposes EXACTLY into two orthogonal terms:
    #     d.cmd = (d.track)(track.cmd) + (d.cross)(cross.cmd)
    # The second is the dodge. The first is the vehicle's ORDINARY FORWARD FLIGHT leaking in through
    # the small angle between the commanded direction and the track normal. Measured on the
    # 2026-08-25 window: +0.0541 m along command = +0.0182 m of real cross-track dodge and
    # +0.0360 m of the -3.95 m cruise leg seen through a 0.52 deg misalignment. TWO THIRDS OF THE
    # HEADLINE "0.54 % COMPLIANCE" IS FORWARD FLIGHT, so the along-command figure may not be quoted
    # as dodge compliance and the cross-track term is reported beside it everywhere.
    track_unit = _unit((v0[0], v0[1]))
    if track_unit is None:
        cross_unit = (0.0, 0.0)
        track_unit = (0.0, 0.0)
    else:
        cross_unit = (-track_unit[1], track_unit[0])
        if cross_unit[0] * cmd_unit[0] + cross_unit[1] * cmd_unit[1] < 0.0:
            cross_unit = (-cross_unit[0], -cross_unit[1])       # point it the way the dodge went
    d_end = enc.flown_path[enc.resume_tick - 1]
    d_vec = (d_end[0] - p0[0], d_end[1] - p0[1])
    d_track = d_vec[0] * track_unit[0] + d_vec[1] * track_unit[1]
    d_cross = d_vec[0] * cross_unit[0] + d_vec[1] * cross_unit[1]
    cruise_leak = d_track * (track_unit[0] * cmd_unit[0] + track_unit[1] * cmd_unit[1])
    dodge_term = d_cross * (cross_unit[0] * cmd_unit[0] + cross_unit[1] * cmd_unit[1])
    misalign_deg = math.degrees(math.acos(max(-1.0, min(1.0, abs(
        cross_unit[0] * cmd_unit[0] + cross_unit[1] * cmd_unit[1])))))

    per_plant = []
    for lim in PLANTS:
        samples = simulate(p0, v0, commands, t0, t_hold, lim, sample_times=want)
        by_t = {round(t, 6): p for t, p in samples}
        mod_window = along(p0, by_t[round(t_resume, 6)])
        mod_hold = along(p0, by_t[round(t_hold, 6)])
        errs = _fit_errors(samples, enc, times)
        per_plant.append({
            "plant": lim.name,
            "modelled_along_cmd_window_m": round(mod_window, 4),
            "modelled_if_guided_continued_m": round(mod_hold, 4),
            "residual_window_m": round(obs_window - mod_window, 4),
            "rms_xy_error_window_m": round(math.sqrt(sum(e * e for e in errs) / len(errs)), 4)
            if errs else None,
            "max_xy_error_window_m": round(max(errs), 4) if errs else None,
        })

    # One-parameter fit: what horizontal accel limit best reproduces the flown window? This is the
    # transfer-gap register's first NUMBER -- what the real SITL vehicle behaved as if it had.
    # Only on the primary command mode; the coarse-then-refine grid keeps it under a second.
    best_a = best_rms = None
    if command_mode == CMD_PRIMARY and fit_a_max:
        best_a, best_rms = _fit_a_max(p0, v0, commands, t0, t_hold, want, enc, times)

    default_fit = next(r for r in per_plant if r["plant"] == GUIDED_DEFAULT.name)
    hypotheses = {
        "H_broken_m": round(ballistic_window, 4),
        "H_plant_m": default_fit["modelled_along_cmd_window_m"],
        "H_compliant_m": round(cmd_dist, 4),
    }
    winner = min(hypotheses, key=lambda k: abs(obs_window - hypotheses[k]))

    # CAN this window tell the hypotheses apart at all? On a 0.434 s window a working command path
    # and a dead one differ by MILLIMETRES, and the telemetry is quantised at ~9 mm by the geodetic
    # round-trip -- so "nearest hypothesis" there is a coin-flip dressed as a finding. Measured on
    # the 2026-08-25 take: 5 mm of separation, 0.6 quanta, and the two command modes return
    # OPPOSITE winners (H_plant under `as_commanded`, H_broken under `latched_first`) off the same
    # telemetry. The quantum is taken ALONG THE COMMANDED DIRECTION, because that is the axis the
    # claim is made on and the two ENU axes have different quanta (E 0.009078 m, N 0.011131 m).
    quantum = _command_axis_quantum_m(enc, cmd_unit)
    separation = abs(hypotheses["H_plant_m"] - hypotheses["H_broken_m"])
    quanta = separation / quantum if quantum else None
    if quanta is None:
        power = "UNKNOWN"
    elif quanta < 4.0:
        power = "NOT DISCRIMINATING"
    elif quanta < 10.0:
        power = "MARGINAL"
    else:
        power = "DISCRIMINATING"
    discriminating = power == "DISCRIMINATING"

    # THE QUESTION Q1 IS ACTUALLY ASKING -- and it is TERNARY, not binary. Over a window long enough
    # for the plant to arrive, H_plant and H_compliant converge and "which is nearest" stops meaning
    # anything, but both mean the same thing: the setpoint reached the vehicle and the vehicle moved.
    # Only H_broken says otherwise. So the useful reading is "did the command path move the
    # aircraft" -- EXCEPT on a window that cannot separate the hypotheses at all, where the honest
    # answer is neither True nor False but UNANSWERABLE. It has to be a third value and not a
    # default of False, because an argmin over hypotheses 5 mm apart was being printed as
    # "THE COMMAND PATH MOVED THE AIRCRAFT on 3 of 5 windows" beside that same row's own
    # EVIDENCE INSUFFICIENT verdict (QA finding C2, 2026-08-26). MARGINAL counts as unanswerable
    # too: 4-10 quanta is not enough to carry a causal claim into an ADR.
    command_path_worked = (winner != "H_broken_m") if discriminating else None

    # How well does the BEST plant reproduce the path, as a fraction of the distance actually
    # flown in the window? A relative statistic, because an rms of 0.6 m is excellent over 22 m of
    # travel and hopeless over 4 m.
    path_len = 0.0
    prev = None
    for tick in range(enc.takeover_tick, enc.resume_tick + 1):
        cur = enc.flown_path[tick - 1] if tick - 1 < len(enc.flown_path) else None
        if cur is not None and prev is not None:
            path_len += math.dist(cur[:2], prev[:2])
        prev = cur if cur is not None else prev
    rms_rows = [r for r in per_plant if r["rms_xy_error_window_m"] is not None]
    best_plant = min(rms_rows, key=lambda r: r["rms_xy_error_window_m"]) if rms_rows else None
    frac = (best_plant["rms_xy_error_window_m"] / path_len
            if best_plant and path_len > 1e-6 else None)
    shape, verdict = _fit_verdict(power, quanta, separation, frac)

    return {
        "timing_axis": axis["label"],
        "timing_kind": axis["kind"],
        "timing_source": axis["source"],
        # An inadmissible axis implies a cruise speed the plant forbids. Kept visible, never
        # aggregated -- see `axis_admissible` and QA finding G77.
        "timing_admissible": bool(axis.get("admissible", True)),
        "timing_implied_cruise_speed_mps": axis.get("implied_cruise_speed_mps"),
        "command_mode": command_mode,
        "n_setpoints_sent": len(sent),
        "setpoint_recession_m": round(math.dist(sent[-1][1][:2], sent[0][1][:2]), 3),
        "window_ticks": [enc.takeover_tick, enc.resume_tick],
        "window_s": round(t_resume - t0, 4),
        "entry_position_enu": [round(c, 4) for c in p0],
        "entry_velocity_mps": [round(c, 4) for c in v0],
        "entry_speed_mps": round(math.hypot(v0[0], v0[1]), 4),
        "entry_window_s": entry_window_s,
        # An ESTIMATE, and on a staircase log a fragile one -- see `entry_velocity_sweep` on the
        # flight entry for how much it moves with the window, and `timing_robustness` for whether
        # the verdict survives every value of it.
        "entry_speed_by_window_mps": {
            f"{w:g}": round(math.hypot(*velocity_at(times, enc.flown_path, t0, window_s=w)[:2]), 4)
            for w in ENTRY_VELOCITY_WINDOWS_S},
        "first_setpoint_enu": [round(c, 4) for c in sent[0][1]],
        "commanded_distance_m": round(cmd_dist, 4),
        "commanded_unit_xy": [round(c, 4) for c in cmd_unit],
        "observed_along_cmd_window_m": round(obs_window, 4),
        "observed_along_cmd_settled_m": round(obs_settled, 4),
        # NOT quotable as dodge compliance -- see the cruise-leak decomposition below.
        "observed_compliance_window_pct": (round(100.0 * obs_window / cmd_dist, 3)
                                           if cmd_dist > 1e-9 else None),
        "observed_compliance_settled_pct": (round(100.0 * obs_settled / cmd_dist, 3)
                                            if cmd_dist > 1e-9 else None),
        "observed_cross_track_m": round(d_cross, 4),
        "observed_along_track_m": round(d_track, 4),
        "cmd_vs_track_normal_deg": round(misalign_deg, 3),
        "along_cmd_decomposition_m": {"dodge_term": round(dodge_term, 4),
                                      "cruise_leak_term": round(cruise_leak, 4)},
        "cross_track_compliance_pct": (round(100.0 * d_cross / cmd_dist, 3)
                                       if cmd_dist > 1e-9 else None),
        "ballistic_along_cmd_window_m": round(ballistic_window, 4),
        "plants": per_plant,
        "hypotheses_along_cmd_m": hypotheses,
        "nearest_hypothesis": winner,
        "command_path_worked": command_path_worked,
        "hypothesis_separation_m": round(separation, 4),
        "position_quantum_m": round(quantum, 6) if quantum is not None else None,
        "hypothesis_separation_quanta": round(quanta, 2) if quanta is not None else None,
        "discriminating_power": power,
        "discriminating": discriminating,
        "window_path_length_m": round(path_len, 3),
        "best_plant_by_rms": best_plant["plant"] if best_plant else None,
        "best_rms_m": best_plant["rms_xy_error_window_m"] if best_plant else None,
        "best_rms_frac_of_path": round(frac, 4) if frac is not None else None,
        "rms_shape_verdict": shape,      # what the rms ALONE would say, always sub-ordinate to
        "fit_verdict": verdict,          # `fit_verdict`, which gates it on discriminating power
        "fitted_a_max_ne_mps2": round(best_a, 3) if best_a is not None else None,
        "fitted_a_max_rms_m": round(best_rms, 4) if best_rms is not None else None,
    }


def _fit_verdict(power: str, quanta: Optional[float], separation_m: float,
                 frac: Optional[float]) -> Tuple[str, str]:
    """(rms-only shape verdict, the verdict that may actually be quoted).

    THE LADDER, and the order is the whole point: DISCRIMINATING POWER COMES FIRST and
    short-circuits everything below it. A low rms only says "the model tracks this path", and on a
    window where EVERY hypothesis tracks the path to within the telemetry quantum that is not
    evidence for any of them -- the 2026-08-25 window scores 1.5 % rms while separating H_plant
    from H_broken by 5 mm. A MARGINAL window used to print "FIT ... [MARGINAL]", which reads as a
    fit with a footnote and got quoted as a fit; it now prints EVIDENCE THIN and carries the rms
    reading as subordinate context, so nothing sub-threshold can be quoted as a fit (QA finding C2).

    A pure function of four numbers so every branch is reachable from a test -- an earlier inline
    version left the MARGINAL branch un-exercised by any fixture, and a branch no test can reach is
    a branch that can be rewritten to say FIT without anything going red."""
    if frac is None:
        shape = "NO-FIT -- the window has no usable telemetry to score against"
    elif frac <= 0.10:
        shape = "FIT -- a default-limited plant reproduces the flown window"
    elif frac <= 0.25:
        shape = "PARTIAL -- the plant explains the shape but not the magnitude"
    else:
        shape = "NO-FIT -- no default-parameter plant reproduces this window"
    headline = shape.split(" --")[0]
    if power == "NOT DISCRIMINATING":
        return shape, (f"EVIDENCE INSUFFICIENT -- the window separates H_plant from H_broken by "
                       f"only {quanta:.1f} telemetry quanta ({separation_m * 1000:.0f} mm); the "
                       f"rms would say '{headline}' but it cannot distinguish the hypotheses")
    if power == "MARGINAL":
        return shape, (f"EVIDENCE THIN -- {quanta:.1f} telemetry quanta of separation is not "
                       f"enough to carry a causal claim; rms alone would say '{headline}'")
    if power != "DISCRIMINATING":
        return shape, "EVIDENCE INSUFFICIENT -- the telemetry quantum could not be measured"
    return shape, shape


def _axis_quanta_m(enc: Encounter) -> Tuple[Optional[float], Optional[float]]:
    """(East quantum, North quantum): the smallest real step each ENU axis of the flown path takes.

    `/ap/pose/filtered` reaches this log through a geodetic round-trip and the two axes come out
    quantised DIFFERENTLY -- measured on all three committed flights, E 0.009078 m and N 0.011131 m
    (the E value is the longitude step scaled by cos(latitude); the N value is the raw 1e-7 deg
    latitude step). The E axis's next step size up is exactly 5x its quantum, which is what makes it
    recognisable as a quantum rather than a small motion. Any displacement claim smaller than a few
    of these is a claim about rounding, which is the whole reason the 0.018 m figure from the
    2026-08-25 window needs this number printed beside it.

    The 1e-4 m floor discards float-representation noise (a handful of 1e-6 m differences survive
    the round-trip); without it the estimator returns the noise instead of the quantum, and every
    window then claims to be discriminating."""
    out = []
    for axis in (0, 1):
        steps = sorted(abs(b[axis] - a[axis])
                       for a, b in zip(enc.flown_path, enc.flown_path[1:])
                       if a is not None and b is not None and abs(b[axis] - a[axis]) > 1e-4)
        out.append(steps[0] if steps else None)
    return out[0], out[1]


def _command_axis_quantum_m(enc: Encounter, cmd_unit) -> Optional[float]:
    """The telemetry's resolution ALONG the commanded direction -- the axis every Q1 displacement
    claim is actually made on.

    Worst case over the two quantised axes: |ux|*q_E + |uy|*q_N. Using one global minimum instead
    (the first version) understates the resolution of a north-south command by 18 %, which is
    exactly the direction that flatters a discrimination test."""
    qe, qn = _axis_quanta_m(enc)
    if qe is None and qn is None:
        return None
    qe = qe if qe is not None else qn
    qn = qn if qn is not None else qe
    return abs(cmd_unit[0]) * qe + abs(cmd_unit[1]) * qn


def _fit_a_max(p0, v0, commands, t0, t_hold, want, enc, times):
    """Grid search for the horizontal accel limit that best reproduces the flown window."""
    def rms_for(a: float) -> Optional[float]:
        lim = PlantLimits(name=f"fit_a{a:.2f}", v_max_ne_mps=GUIDED_DEFAULT.v_max_ne_mps,
                          a_max_ne_mps2=a, jerk_ne_mps3=GUIDED_DEFAULT.jerk_ne_mps3,
                          v_max_up_mps=GUIDED_DEFAULT.v_max_up_mps,
                          v_max_down_mps=GUIDED_DEFAULT.v_max_down_mps,
                          a_max_u_mps2=GUIDED_DEFAULT.a_max_u_mps2,
                          jerk_u_mps3=GUIDED_DEFAULT.jerk_u_mps3, pos_p=GUIDED_DEFAULT.pos_p,
                          provenance="one-parameter fit, NOT a default")
        errs = _fit_errors(simulate(p0, v0, commands, t0, t_hold, lim, sample_times=want),
                           enc, times)
        return math.sqrt(sum(e * e for e in errs) / len(errs)) if errs else None

    best_a = best_rms = None
    for step, span in ((0.25, [0.1 + 0.25 * i for i in range(24)]), (0.05, None)):
        grid = span if span is not None else [max(0.05, best_a - 0.25) + 0.05 * i
                                              for i in range(11)]
        for a in grid:
            r = rms_for(a)
            if r is not None and (best_rms is None or r < best_rms):
                best_a, best_rms = a, r
        if best_a is None:
            break
    return best_a, best_rms


# ============================================================ Q2: the counterfactual escape sweep
def escape_candidates(drone_xy, drone_z: float, bird_xy, heading_unit,
                      params: dict) -> List[Tuple[str, Tuple[float, float, float]]]:
    """Every escape the sweep considers, as (label, setpoint ENU).

    The seven LATERAL headings are generated by the policy's own `_CANDIDATE_ANGLES_DEG` /
    `_rotate` / `_unit` against the same away-from-bird vector, so "candidate ordering" is swept over
    exactly the set the policy would have chosen from -- 0 deg is the straight-away REVERSAL the
    policy prefers first. Three escapes the policy does NOT have are added, because the point of a
    counterfactual is to price options the current control law cannot take:
      * `climb`     -- straight up to the altitude ceiling. ADR-009 refuses to trust a bird's z, and
                       ADR-013 am. 18 warns that a climb which merely leaves the +/-6 m band prints
                       `gt_cpa_m NONE-IN-BAND`, a green that means "not measured", so the report
                       always names a climb result as band-exit rather than clearance.
      * `brake`     -- hold position: the speed-brake-to-hover escape.
      * `sidestep_ahead_+/-90` -- lateral offset applied to a point AHEAD along track, which is the
                       one escape that does not ask the controller to arrest the cruise leg. The
                       accel budget is shared as a vector, so a dodge that also demands a stop gets
                       roughly half of it; this candidate exists to measure that penalty."""
    away = _unit((drone_xy[0] - bird_xy[0], drone_xy[1] - bird_xy[1]))
    if away is None:
        away = (-heading_unit[1], heading_unit[0])      # bird directly underfoot -> sidestep
    divert = float(params.get("divert_distance_m", 10.0))
    cruise = float(params.get("cruise_alt_m", 15.0))
    alt_max = float((params.get("alt_bounds") or [2.0, 30.0])[1])
    out: List[Tuple[str, Tuple[float, float, float]]] = []
    for angle in _CANDIDATE_ANGLES_DEG:
        d = _rotate(away, angle)
        out.append((f"lateral_{angle:+.0f}",
                    (drone_xy[0] + d[0] * divert, drone_xy[1] + d[1] * divert, cruise)))
    out.append(("climb", (drone_xy[0], drone_xy[1], alt_max)))
    out.append(("brake", (drone_xy[0], drone_xy[1], drone_z)))
    for angle in (90.0, -90.0):
        d = _rotate(away, angle)
        out.append((f"sidestep_ahead_{angle:+.0f}",
                    (drone_xy[0] + d[0] * divert + heading_unit[0] * divert,
                     drone_xy[1] + d[1] * divert + heading_unit[1] * divert, cruise)))
    return out


def counterfactual_sweep(enc: Encounter, axis: dict, geofence: GeofenceMap) -> dict:
    """lead time x candidate x plant, each cell scored by the gate's own CPA against the real bird.

    The FLOWN path is scored by the same function first, so every counterfactual in the table is
    read against the number the flight actually produced rather than against an intuition."""
    times = axis["times"]
    bar = float(enc.params.get("min_bird_clearance_m", PolicyParams().min_bird_clearance_m))
    tree_margin = float(enc.params.get("lateral_tree_margin_m", 0.0))
    t_takeover = times[enc.takeover_tick - 1]
    t_resume = times[enc.resume_tick - 1]
    # WHERE EACH CELL'S SIMULATION ENDS, and the reasoning has been wrong once in each direction.
    #
    # The end is ABSOLUTE, not measured from the command. THE BIRD ARRIVES WHEN IT ARRIVES: its
    # trajectory is nailed to sim time, so the only thing a simulated window has to do is CONTAIN
    # THE ENCOUNTER. An equal-duration-after-the-command rule (a fix for QA's m8, which was itself
    # wrong and is retracted here) ends a lead-3.0 cell at t_takeover + horizon - 3.0 s, which on
    # the 2026-08-25 encounter is 0.434 s past takeover -- the bird has not arrived yet, nothing is
    # scored, and the cell reports enormous separation. Measured when that rule was live: 72 of 429
    # cells changed and 32 flipped resolved False -> True, e.g. lead-3.0 climb/poscontrol_bare
    # reporting min_horizontal_threat_m 12.55 m where an encounter-covering window gives 0.50 m.
    # That is C3's vacuous green relocated from vertical scoping to temporal scoping, and it is
    # exactly as dangerous: an escape "resolves" because the encounter was never simulated.
    #
    # `max(t_cmd, t_takeover)` rather than plain `t_takeover` so a NEGATIVE lead (a warning that
    # arrives LATE, which the grid does not use today but is the obvious next question) still gets
    # a full horizon after its own command instead of a truncated one.
    #
    # The consequence -- long-lead cells simulate for LONGER -- is correct, not a bias: they started
    # earlier, so they have been flying longer by the time the bird arrives. Comparability across
    # leads lives in the encounter being covered by all of them, not in equal stopwatch time.
    # `covers_flown_cpa` is asserted on every row so this cannot silently regress again.
    horizon_s = min(t_resume + 3.0, times[-1]) - t_takeover
    history_s = t_takeover - times[0]
    vertical_threat = float(enc.params.get("vertical_threat_m", 6.0))

    flown = [(times[i], enc.flown_path[i]) for i in range(len(enc.flown_path))
             if enc.flown_path[i] is not None and i < len(times)]
    flown_rep = cpa_of(flown, enc.truth, enc.params)
    # The sim instant the real encounter actually happened at. Every counterfactual window must
    # contain it or the cell measured nothing about this encounter -- see the horizon comment.
    t_cpa = flown_rep["t_sim_s"]

    rows: List[dict] = []
    for lead in LEAD_GRID_S:
        if lead > history_s - 0.2:
            continue
        t_cmd = t_takeover - lead
        p0 = sample_at(times, enc.flown_path, t_cmd)
        v0 = velocity_at(times, enc.flown_path, t_cmd)
        heading = _unit((v0[0], v0[1])) or (0.0, 1.0)
        if p0 is None:
            continue
        try:
            bird_id, _bz = _threat_bird_at(enc, t_cmd, p0)
        except ValueError:
            continue
        bird = _bird_xy(enc, bird_id, t_cmd, near=p0)
        if bird is None:
            continue
        t_end = max(t_cmd, t_takeover) + horizon_s
        covers_cpa = bool(t_cpa is None or t_cmd <= t_cpa <= t_end)
        for label, sp in escape_candidates((p0[0], p0[1]), p0[2], bird, heading, enc.params):
            swept = geofence.segment_clearance((p0[0], p0[1]), (sp[0], sp[1])).clearance_m
            legal, why = _setpoint_legal(sp, swept, tree_margin, enc.params)
            for lim in PLANTS:
                samples = simulate(p0, v0, [(t_cmd, sp)], t_cmd, t_end, lim, sample_dt_s=0.02)
                rep = cpa_of(samples, enc.truth, enc.params)
                cpa = rep["gt_cpa_m"]
                passed = _passed_bird(samples, enc, bird_id, heading)
                band, min_horiz = _band_audit(samples, enc, bird_id, vertical_threat)
                cleared = bool(cpa is not None and cpa >= bar and band == "in_band")
                resolved_physically = bool(cleared and passed)
                rows.append({
                    "lead_s": lead, "candidate": label, "plant": lim.name,
                    "setpoint_enu": [round(c, 3) for c in sp],
                    "gt_cpa_m": round(cpa, 4) if cpa is not None else None,
                    "min_horizontal_any_band_m": round(rep["min_horizontal_any_band_m"], 4)
                    if rep["min_horizontal_any_band_m"] is not None else None,
                    # The band-free horizontal minimum to the THREAT bird. Printed on every row
                    # because a band-scoped CPA without it is the pre-registered vacuous green.
                    "min_horizontal_threat_m": round(min_horiz, 4) if min_horiz is not None
                    else None,
                    "band": band,
                    "band_exit": band != "in_band",
                    "cleared": cleared,
                    "passed_bird": passed,
                    "resolved_physically": resolved_physically,
                    "resolved_legally": bool(resolved_physically and legal),
                    "binding_constraint": ("plant/lead" if not resolved_physically
                                           else ("tree/field vet" if not legal else None)),
                    "swept_tree_clearance_m": round(swept, 3),
                    "setpoint_legal": legal,
                    "illegal_reason": why,
                    "displacement_m": round(math.dist(samples[-1][1], p0), 4),
                    "simulated_span_s": [round(t_cmd, 3), round(t_end, 3)],
                    "simulated_duration_s": round(t_end - t_cmd, 3),
                    # If this is ever False the cell is not evidence about this encounter.
                    "covers_flown_cpa": covers_cpa,
                })
    return {"timing_axis": axis["label"], "timing_kind": axis["kind"], "bar_m": bar,
            "horizon_after_takeover_s": round(horizon_s, 3),
            "flown_cpa_t_sim_s": round(t_cpa, 4) if t_cpa is not None else None,
            "all_cells_cover_flown_cpa": all(r["covers_flown_cpa"] for r in rows),
            "flown_gt_cpa_m": round(flown_rep["gt_cpa_m"], 4)
            if flown_rep["gt_cpa_m"] is not None else None,
            "flown_cpa_from": flown_rep["cpa_from"],
            "rows": rows, "summary": _cf_summary(rows, bar)}


def _band_audit(samples, enc: Encounter, bird_id: str,
                vertical_threat_m: float) -> Tuple[str, Optional[float]]:
    """("in_band" | "partial_band_exit" | "never_in_band", min horizontal distance to the threat
    bird over the whole horizon, band-free).

    WHY THIS EXISTS (QA finding C3, 2026-08-26). `ground_truth_cpa` is vertically scoped by
    `PolicyParams.vertical_threat_m` -- correctly, because bird_1 and bird_2 patrol 7-9 m below
    cruise and an unscoped bar would fail every flight forever. But a CLIMB escape makes the drone
    LEAVE that band mid-encounter, and the scoped CPA then reports the last in-band instant, which
    is wherever the pair happened to be before the climb took effect. Measured: climb cells
    reported gt_cpa 5.35 / 14.77 / 14.34 / 28.08 m while the true minimum horizontal distance to
    bird_0 over the same trajectory was 0.78 / 0.17 / 0.014 / 0.50 m. That is the exact shape of
    the vacuous green ADR-013 am. 18 pre-registered, and it would have promoted "climb" into the
    resolving-candidate list off a 14 mm pass.

    So a cell that leaves the band is NOT cleared and NOT resolved: it is BAND-EXIT, printed with
    the band-free minimum beside it. A climb also rests on the bird's z, which ADR-009 is explicit
    about not trusting -- so a climb that is only safe because of where we think the bird is
    vertically is not a result this study will hand to an ADR."""
    n_in = n_out = 0
    best: Optional[float] = None
    for t, p in samples:
        cands = enc.truth.candidates_at(t) or {}
        answer = cands.get(bird_id)
        if not answer or not answer.positions:
            continue
        pos = min(answer.positions, key=lambda q: math.hypot(p[0] - q[0], p[1] - q[1]))
        horiz = math.hypot(p[0] - pos[0], p[1] - pos[1])
        best = horiz if best is None else min(best, horiz)
        if abs(p[2] - pos[2]) <= vertical_threat_m:
            n_in += 1
        else:
            n_out += 1
    if n_in == 0:
        return "never_in_band", best
    return ("in_band" if n_out == 0 else "partial_band_exit"), best


_FIELD_POLYGON = None


def _setpoint_legal(sp, swept_clearance_m: float, tree_margin_m: float,
                    params: dict) -> Tuple[bool, Optional[str]]:
    """Would the POLICY have been allowed to command this escape? Trees, field polygon + inward
    margin, and the altitude envelope, checked with the policy's own geometry helpers.

    A counterfactual that clears the bird by leaving the field is not an escape; a sweep that did
    not say so would recommend one. This is a subset of `AvoidancePolicy._vet` -- the bird gates are
    deliberately left out, because the whole point of the sweep is to price escapes the current
    candidate ordering would not pick.

    KNOWN CONSERVATIVE, and reported rather than corrected: the tree check is
    `GeofenceMap.segment_clearance`, which is XY-ONLY, mirroring what the policy itself does. On the
    encounter lane the vehicle is horizontally inside an orchard-row exclusion column while flying
    15 m above a 3.5 m canopy, so this refuses escapes -- including BRAKE -- that are not physically
    obstructed at all. That is why every lead is reported both physically and legally
    (`_cf_summary`): the difference IS this vet, and it must not be smuggled into a claim about the
    aircraft."""
    global _FIELD_POLYGON
    from fieldguard_planning.avoidance_policy import _point_edge_distance, _point_in_polygon
    if _FIELD_POLYGON is None:
        from fieldguard_planning.coverage import load_field_polygon
        _FIELD_POLYGON = load_field_polygon()
    if swept_clearance_m < tree_margin_m:
        return False, (f"swept path clears tree by {swept_clearance_m:.2f} m "
                       f"(< {tree_margin_m:.2f} m required)")
    lo, hi = (params.get("alt_bounds") or [2.0, 30.0])
    if not (float(lo) <= sp[2] <= float(hi)):
        return False, f"setpoint altitude {sp[2]:.2f} m outside alt_bounds [{lo}, {hi}]"
    if not _point_in_polygon(sp[0], sp[1], _FIELD_POLYGON):
        return False, "setpoint outside the field polygon"
    margin = float(params.get("field_margin_m", 1.0))
    edge = _point_edge_distance(sp[0], sp[1], _FIELD_POLYGON)
    if edge < margin:
        return False, f"setpoint {edge:.2f} m from the field edge (< {margin:.2f} m margin)"
    return True, None


def _passed_bird(samples, enc: Encounter, bird_id: str, heading) -> bool:
    """Did the vehicle actually get PAST the bird along its original track inside the horizon?

    Without this test the sweep congratulates itself for retreating. A vehicle told to reverse 10 m
    3 s before a STATIC obstacle simply stops 25 m short, and the CPA function correctly reports
    25 m of separation -- but the encounter has been DEFERRED, not resolved: the mission still has
    to fly that lane. A cell only counts as a genuine clearance when the bar is met AND the
    along-track projection of (bird - drone) went negative, i.e. the bird ended up behind.

    Tracks ONE named bird and ignores the vertical band on purpose: this is a geometry question, not
    a threat question, and a band-scoped version would call a CLIMB "never passed" simply because
    the pair left the band -- scoring a real escape as a deferral."""
    for t, p in samples:
        bird = _bird_xy(enc, bird_id, t, near=p)
        if bird is None:
            continue
        if (bird[0] - p[0]) * heading[0] + (bird[1] - p[1]) * heading[1] < 0.0:
            return True
    return False


def _bird_xy(enc: Encounter, bird_id: str, t: float, near=None):
    """One named bird's horizontal position at absolute time `t`, band-free.

    When the truth track reports a `set_pose` bracket it returns several candidates, and this takes
    the one NEAREST to `near` (the drone) -- the gate's own convention, because uncertainty must not
    buy clearance. With `near=None` it takes the first, which is only correct where the choice
    cannot matter."""
    cands = enc.truth.candidates_at(t) or {}
    answer = cands.get(bird_id)
    if not answer or not answer.positions:
        return None
    pos = (answer.positions[0] if near is None else
           min(answer.positions, key=lambda q: math.hypot(near[0] - q[0], near[1] - q[1])))
    return (pos[0], pos[1])


def _threat_bird_at(enc: Encounter, t: float, drone) -> Tuple[str, float]:
    """(bird_id, z) of the THREAT bird at time `t`: the nearest bird inside the policy's own threat
    cylinder, falling back to the nearest one merely inside the vertical band.

    Picking "the first bird in the dict" or "the lowest bird" would be a real defect on the
    2026-08-25 track, which drives three: bird_1 and bird_2 patrol 7 m and 9 m below cruise and are
    never threats. Measured cost of getting it wrong on the number that matters most -- bird_2's
    9.03 m depth reports a 5.56 m nadir sensor horizon where the threat bird's 4.03 m depth gives
    2.48 m, i.e. more than double, on the single figure the mount decision turns on. Selection uses
    the SAME cylinder test the policy uses (`threat_radius_m`, `vertical_threat_m`)."""
    cands = enc.truth.candidates_at(t) or {}
    radius = float(enc.params.get("threat_radius_m", 12.0))
    vband = float(enc.params.get("vertical_threat_m", 6.0))
    pool = []
    for bird_id, answer in cands.items():
        for pos in answer.positions:
            if abs(drone[2] - pos[2]) > vband:
                continue
            horiz = math.hypot(drone[0] - pos[0], drone[1] - pos[1])
            pool.append((horiz > radius, horiz, bird_id, pos[2]))
    if not pool:
        raise ValueError("no bird inside the threat band at the takeover instant -- the encounter "
                         "cannot be located, so the sensor horizon has no depth to be measured at")
    _outside, _h, bird_id, bird_z = min(pool)
    return bird_id, bird_z




# ================================================== Q3: the tripwire and the ADR-017 speed doctrine
def sensor_horizon_m(intrinsics: dict, depth_m: float) -> dict:
    """Half-footprint of the NADIR camera at `depth_m` below it, from the LIVE camera_info the take
    recorded -- not from `config/ndvi_camera.json` and not from prose (ADR-016 doctrine).

    half_x = (width/2) / fx * depth, half_y = (height/2) / fy * depth. The along-track axis is taken
    as the LARGER of the two, which reproduces the 2.48 m figure ADR-013 am. 18 quotes at the
    encounter's 4.03 m depth.

    BE HONEST ABOUT THAT max(): it does not PREVENT an axis swap, it silently RESOLVES one, and an
    earlier version of this docstring claimed the opposite. Nothing here reads the mount's yaw, so
    if the along-track axis is really the short one the true horizon is the cross-track figure
    (1.86 m, 25 % smaller). It is kept because the direction of the error is the safe one for this
    study's NEGATIVE verdict -- a larger assumed horizon makes "no safe speed exists" harder to
    reach, not easier -- and `axis_taken` records the choice so a reader can invert it. Attack (b)
    in `robustness_attacks` prices the pessimistic alternative outright."""
    fx, fy = float(intrinsics["fx"]), float(intrinsics["fy"])
    w, h = float(intrinsics["image_width_px"]), float(intrinsics["image_height_px"])
    hx, hy = (w / 2.0) / fx * depth_m, (h / 2.0) / fy * depth_m
    return {"depth_m": round(depth_m, 4), "half_footprint_x_m": round(hx, 4),
            "half_footprint_y_m": round(hy, 4), "along_track_m": round(max(hx, hy), 4),
            "cross_track_m": round(min(hx, hy), 4),
            "axis_taken": "x" if hx >= hy else "y",
            "provenance": intrinsics.get("provenance", "run.detector.intrinsics")}


def bird_speed_m_s(bird_id: str) -> float:
    """Scripted ground speed of one bird, from the config the world was generated from -- via the
    gate's own `load_birds`, so the study and the safety gate read one file through one parser."""
    for bird in gate.load_birds(gate.DEFAULT_BIRDS_CONFIG):
        if bird.get("bird_id") != bird_id:
            continue
        wps = bird.get("waypoints") or []
        best = 0.0
        for a, b in zip(wps, wps[1:]):
            dt = float(b["t_s"]) - float(a["t_s"])
            if dt > 0:
                best = max(best, math.dist((a["x_m"], a["y_m"], a["z_m"]),
                                           (b["x_m"], b["y_m"], b["z_m"])) / dt)
        return best
    raise KeyError(bird_id)


def tripwire(horizon: dict, bar_m: float, bird_mps: float, vertical_threat_m: float,
             vertical_gap_m: float) -> dict:
    """ADR-016 tripwire (a) and the ADR-017 speed doctrine, in one computation.

    THE GEOMETRY, stated so the answer can be checked by hand. On the flown encounter the bird
    patrols the SAME lane the drone surveys (orchard row 0, x = 15 m), head-on. Horizontal
    separation at closest approach is therefore ~0 unless the drone moves SIDEWAYS off the lane by
    the full bar. The lead available is bounded by how far ahead the nadir camera can see the bird
    at its own depth, divided by the closing speed -- and the closing speed can never fall below the
    BIRD's own 6 m/s, however slowly the drone flies. That last clause is why the speed doctrine has
    a floor, and it is the whole answer to "is there a safe speed?"."""
    reach = horizon["along_track_m"]
    rows = []
    safe_speeds = []
    for v in SPEED_SWEEP_MPS:
        closing = v + bird_mps
        lead = reach / closing
        cell = {"mission_speed_mps": v, "closing_speed_mps": round(closing, 3),
                "max_lead_s": round(lead, 4), "plants": {}}
        for lim in PLANTS:
            reachable = max_displacement_m(lead, lim)
            need_s = time_to_displace_s(bar_m, lim)
            cell["plants"][lim.name] = {
                "max_lateral_displacement_m": round(reachable, 4),
                "cleared": bool(reachable >= bar_m),
                "required_lead_s": round(need_s, 4) if need_s is not None else None,
                "required_sensor_horizon_m": round(need_s * closing, 3)
                if need_s is not None else None,
            }
        cell["cleared_by_any_plant"] = any(p["cleared"] for p in cell["plants"].values())
        if cell["cleared_by_any_plant"]:
            safe_speeds.append(v)
        rows.append(cell)

    # The limit case: however slowly the drone flies, the bird still closes at its own speed, so the
    # lead time has a hard ceiling. If the bar is unreachable HERE it is unreachable at any speed.
    lead_ceiling = reach / bird_mps
    ceiling = {}
    for lim in PLANTS:
        d = max_displacement_m(lead_ceiling, lim)
        ceiling[lim.name] = {"max_lateral_displacement_m": round(d, 4),
                             "cleared": bool(d >= bar_m)}

    # A climb does not create horizontal separation; it can only leave the threat band, which the
    # gate then reports as NONE-IN-BAND. Priced separately and labelled as such.
    climb_needed = max(0.0, vertical_threat_m - vertical_gap_m)
    climb = {}
    for lim in PLANTS:
        t_needed = _time_to_climb_s(climb_needed, lim)
        climb[lim.name] = {
            "climb_needed_m": round(climb_needed, 3),
            "time_to_exit_band_s": round(t_needed, 4) if t_needed is not None else None,
        }

    return {
        "bar_m": bar_m,
        "sensor_horizon": horizon,
        "bird_speed_mps": round(bird_mps, 4),
        "speed_sweep": rows,
        "safe_speed_band_mps": [min(safe_speeds), max(safe_speeds)] if safe_speeds else None,
        # THE FIELD ADR-017 READS. "Fly no faster than this on the encounter lane", or None -- and
        # None is the answer, not a gap to be filled by interpolating the sweep. Clearing is
        # monotone in speed (slower -> more lead -> more escape), so the maximum clearing speed IS
        # the doctrine's number when one exists.
        "max_safe_speed_mps": max(safe_speeds) if safe_speeds else None,
        "safe_speed_exists_in_2_10": bool(safe_speeds),
        "why_no_safe_speed": (None if safe_speeds else
                              f"the closing speed cannot fall below the bird's own "
                              f"{bird_mps:.2f} m/s, so lead is capped at {reach:.3f} m / "
                              f"{bird_mps:.2f} m/s = {reach / bird_mps:.4f} s however slowly the "
                              f"drone flies -- and no plant, including the ANGLE_MAX ceiling, can "
                              f"move {bar_m:.2f} m sideways in that time."),
        "hover_limit": {"max_lead_s": round(lead_ceiling, 4),
                        "note": "mission speed 0: the bird alone sets the closing speed, so this "
                                "is the most lead nadir geometry can EVER give on this encounter",
                        "plants": ceiling,
                        "cleared_by_any_plant": any(p["cleared"] for p in ceiling.values())},
        "climb_escape": {"note": "a climb buys no HORIZONTAL separation; clearing the +/-"
                                 f"{vertical_threat_m:g} m band makes the gate print NONE-IN-BAND, "
                                 "which ADR-013 am. 18 requires be read as 'not measured', not as a "
                                 "pass", "plants": climb},
        "robustness_attacks": _tripwire_attacks(horizon, bar_m, bird_mps, vertical_threat_m),
    }


def _tripwire_attacks(horizon: dict, bar_m: float, bird_mps: float,
                      vertical_threat_m: float) -> dict:
    """Three attacks on the "no safe speed" verdict, carried IN the artifact rather than in a
    reviewer's notes, because each of them is the obvious way to try to overturn it.

    All three are computed at the HOVER LIMIT -- the most generous lead nadir geometry can ever
    give, since the closing speed floor is the bird's own. Each is an additive read; none of them
    touches the speed-sweep computation.

    (a) ALTITUDE. The footprint scales with depth, so flying higher above the bird buys horizon.
        Swept across the whole +/-`vertical_threat_m` band -- because outside it the pair is not a
        threat by the policy's own definition, and "safe because we left the band" is the vacuous
        green again.
    (b) AXIS CHOICE. `sensor_horizon_m` takes max(half_x, half_y). If the mount's along-track axis
        is really the SHORT one the true horizon is 25 % smaller and every number here gets worse.
        Optimistic is the conservative direction for a NEGATIVE verdict, and this says so.
    (c) ANGLE_MAX. The 30 deg default is a parameter; raising it to the practical acro limit of
        45 deg raises the lateral-accel ceiling by 73 %."""
    fx_ratio = horizon["along_track_m"] / horizon["depth_m"] if horizon["depth_m"] else 0.0
    ceiling = max(PLANTS, key=lambda p: p.a_max_ne_mps2)
    alt_rows = []
    for depth in [round(0.5 * i, 1) for i in range(1, int(vertical_threat_m / 0.5) + 1)]:
        reach = fx_ratio * depth
        lead = reach / bird_mps
        best = max(max_displacement_m(lead, lim) for lim in PLANTS)
        alt_rows.append({"depth_m": depth, "sensor_horizon_m": round(reach, 4),
                         "max_lead_s": round(lead, 4),
                         "best_lateral_m": round(best, 4), "cleared": bool(best >= bar_m)})
    best_alt = max(alt_rows, key=lambda r: r["best_lateral_m"]) if alt_rows else None
    # What depth the CEILING plant would need for the bar to be reachable at the hover limit.
    need_s = time_to_displace_s(bar_m, ceiling)
    depth_needed = (need_s * bird_mps / fx_ratio) if (need_s and fx_ratio) else None

    steep = PlantLimits(name="angle_max_45deg", v_max_ne_mps=ceiling.v_max_ne_mps,
                        a_max_ne_mps2=G_M_S2 * math.tan(math.radians(45.0)),
                        jerk_ne_mps3=ceiling.jerk_ne_mps3, v_max_up_mps=ceiling.v_max_up_mps,
                        v_max_down_mps=ceiling.v_max_down_mps,
                        a_max_u_mps2=ceiling.a_max_u_mps2, jerk_u_mps3=ceiling.jerk_u_mps3,
                        pos_p=ceiling.pos_p, provenance="attack (c): ANGLE_MAX raised to 45 deg")
    hover_lead = horizon["along_track_m"] / bird_mps
    steep_reach = max_displacement_m(hover_lead, steep)
    return {
        "a_altitude_sweep": {
            "note": (f"depth swept over the whole +/-{vertical_threat_m:g} m threat band at the "
                     f"hover-limit closing speed ({bird_mps:.3f} m/s), the most generous case"),
            "rows": alt_rows,
            "best": best_alt,
            "shortfall_factor_at_best": (round(bar_m / best_alt["best_lateral_m"], 2)
                                         if best_alt and best_alt["best_lateral_m"] > 0 else None),
            "depth_needed_by_ceiling_plant_m": round(depth_needed, 2) if depth_needed else None,
            "depth_needed_is_outside_band": bool(depth_needed
                                                 and depth_needed > vertical_threat_m),
        },
        "b_axis_choice": {
            "note": ("sensor_horizon_m takes max(half_x, half_y) = the LONGER half-footprint as "
                     "along-track. If the mount's along-track axis is the shorter one the true "
                     "horizon is the cross-track figure and every result here is optimistic."),
            "along_track_taken_m": horizon["along_track_m"],
            "pessimistic_alternative_m": horizon["cross_track_m"],
            "direction": ("OPTIMISTIC, therefore CONSERVATIVE for a negative verdict: the smaller "
                          "horizon makes 'no safe speed' more true, not less"),
        },
        "c_angle_max_45deg": {
            "note": "ANGLE_MAX raised from its 30 deg default to a 45 deg acro limit",
            "a_max_ne_mps2": round(steep.a_max_ne_mps2, 4),
            "max_lead_s": round(hover_lead, 4),
            "max_lateral_m": round(steep_reach, 4),
            "cleared": bool(steep_reach >= bar_m),
            "shortfall_factor": round(bar_m / steep_reach, 2) if steep_reach > 0 else None,
        },
    }


def _time_to_climb_s(dz_m: float, lim: PlantLimits, t_max: float = 60.0) -> Optional[float]:
    """Shortest time to gain `dz_m` of altitude at full vertical authority (jerk ramp, accel cap,
    climb-rate cap). Same closed form as `max_displacement_m` on the vertical limits."""
    if dz_m <= 0.0:
        return 0.0
    vert = PlantLimits(name="v", v_max_ne_mps=lim.v_max_up_mps, a_max_ne_mps2=lim.a_max_u_mps2,
                       jerk_ne_mps3=lim.jerk_u_mps3, v_max_up_mps=lim.v_max_up_mps,
                       v_max_down_mps=lim.v_max_down_mps, a_max_u_mps2=lim.a_max_u_mps2,
                       jerk_u_mps3=lim.jerk_u_mps3, pos_p=lim.pos_p, provenance="vertical view")
    return time_to_displace_s(dz_m, vert, t_max_s=t_max)


