def _wrap(text: str, width: int) -> List[str]:
    words, lines, cur = str(text).split(), [], ""
    for word in words:
        if cur and len(cur) + 1 + len(word) > width:
            lines.append(cur)
            cur = word
        else:
            cur = f"{cur} {word}".strip()
    if cur:
        lines.append(cur)
    return lines


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--logs", nargs="*", type=Path,
                    help="flight logs to replay (default: every committed live flight log)")
    ap.add_argument("--out", type=Path, help="results JSON path (default: eval/results/"
                                             "replay_point_mass_<UTC>.json)")
    ap.add_argument("--json-only", action="store_true", help="write the artifact, print nothing")
    args = ap.parse_args(argv)

    paths = list(args.logs) if args.logs else sorted(RESULTS_DIR.glob("live_flight_log_*.json"))
    paths = [p for p in paths if p.is_file()]
    if not paths:
        print("no live flight logs found -- nothing to replay", file=sys.stderr)
        return 2

    rep = build_report(paths)
    stamp = rep["generated_utc"].replace("-", "").replace(":", "")
    out = args.out or (RESULTS_DIR / f"replay_point_mass_{stamp}.json")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(rep, indent=2, sort_keys=False) + "\n")
    if not args.json_only:
        print_report(rep)
        print(f"\nresults JSON -> {out}")
    # EXIT CODES. A study enforces no bar, so a completed replay is 0 whatever it found -- but a
    # replay that scored NOTHING is not a result, it is a broken instrument, and the first version
    # exited 0 with an empty table (QA finding M1). Every skip is named in the artifact and on
    # stderr regardless, because a hole in the denominator that only the JSON knows about is the
    # failure mode this whole project keeps re-learning.
    for s in rep["logs_skipped"]:
        print(f"WARNING: skipped {s['log']}: {s['reason']}", file=sys.stderr)
    if not rep["flights"]:
        print(f"NO FLIGHT COULD BE REPLAYED: all {len(paths)} log(s) were skipped (reasons above). "
              f"This is an instrument failure, not an empty result.", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
