def _fmt(x, places=4, dash="  --  "):
    return dash if x is None else f"{x:.{places}f}"


def build_report(log_paths: Sequence[Path]) -> dict:
    geofence = GeofenceMap.from_file()
    bar = PolicyParams().min_bird_clearance_m
    flights = []
    encounters: List[Encounter] = []
    skipped: List[dict] = []
    for p in log_paths:
        enc, reason = load_encounter(p)
        if enc is None:
            skipped.append({"log": Path(p).name, "reason": reason})
            continue
        encounters.append(enc)

    for enc in encounters:
        axes = timing_axes(enc)
        attach_truth(enc, [t for a in axes for t in (a["times"][0], a["times"][-1])])
        entry = {
            "stem": enc.stem,
            "schema_version": enc.schema_version,
            "n_maneuvers": enc.n_maneuvers,
            "window_ticks": [enc.takeover_tick, enc.resume_tick],
            "truth_kind": enc.truth_kind,
            "truth_path": (Path(enc.truth.path).name
                           if getattr(enc.truth, "path", None) else "logged demo-bird position"),
            "policy_params": enc.params,
            "timing_axes": [{"label": a["label"], "kind": a["kind"], "source": a["source"]}
                            for a in axes],
            "plant_fit": [],
            "counterfactual": [],
        }
        if enc.truth_kind == "applied_pose_truth_track":
            span = enc.truth.span
            t0, t1 = axes[0]["times"][0], axes[0]["times"][-1]
            entry["truth_span_s"] = [round(span[0], 3), round(span[1], 3)]
            entry["flight_tick_span_s"] = [round(t0, 3), round(t1, 3)]
            entry["trusted_span_s"] = [round(max(span[0], t0), 3), round(min(span[1], t1), 3)]
            entry["trusted_span_note"] = (
                "ADR-012 am. 3: this applied-pose track GREW after the flight (1348 -> 2202 "
                "records, frozen at 2202). Only the flight's own tick span is trustworthy; the "
                "replay reads the truth track ONLY inside the encounter window "
                f"(~{axes[0]['times'][enc.takeover_tick - 1] - 4.0:.1f}-"
                f"{axes[0]['times'][enc.resume_tick - 1] + 4.0:.1f} s), which sits well inside it.")
        for axis in axes:
            for mode in (CMD_LATCHED, CMD_AS_SENT):
                entry["plant_fit"].append(plant_fit(enc, axis, mode))
            entry["counterfactual"].append(counterfactual_sweep(enc, axis, geofence))
        entry["step_diagnostic"] = step_diagnostic(enc, axes)
        entry["entry_velocity_sweep_mps"] = {
            a["label"]: {f"{w:g}s": round(math.hypot(*velocity_at(
                a["times"], enc.flown_path, a["times"][enc.takeover_tick - 1], window_s=w)[:2]), 4)
                for w in ENTRY_VELOCITY_WINDOWS_S} for a in axes}
        entry["timing_robustness"] = timing_robustness(enc, axes)
        flights.append(entry)

    # ---- Q3 is computed from the ONE flight that carries live intrinsics and a moving real bird.
    schema2 = [e for e in encounters if e.truth_kind == "applied_pose_truth_track"]
    trip = None
    if schema2:
        enc = schema2[0]
        det = (enc.log.get("run") or {}).get("detector") or {}
        intr = det.get("intrinsics") or {}
        axis = timing_axes(enc)[0]
        t_tk = axis["times"][enc.takeover_tick - 1]
        drone = enc.flown_path[enc.takeover_tick - 1]
        # THE THREAT BIRD, selected by the policy's own cylinder test. Picking "the lowest bird" or
        # "the first in the dict" would have taken bird_2's 9 m depth here and reported a 5.56 m
        # sensor horizon -- more than twice the truth, on the one number the mount decision turns on.
        bird_id, bird_z = _threat_bird_at(enc, t_tk, drone)
        depth = abs(drone[2] - bird_z)
        trip = tripwire(sensor_horizon_m(intr, depth), bar, bird_speed_m_s(bird_id),
                        float(enc.params.get("vertical_threat_m", 6.0)), depth)
        trip["measured_from"] = {
            "flight": enc.stem, "bird_id": bird_id,
            "drone_z_m": round(drone[2], 3), "bird_z_m": round(bird_z, 3),
            "depth_m": round(depth, 3),
            "flown_speed_mps": round(math.hypot(*velocity_at(axis["times"], enc.flown_path,
                                                             t_tk)[:2]), 3),
        }

    return {
        "tool": "eval/replay_point_mass.py",
        "generated_utc": _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "mandate": "ADR-016 (Council Ruling 001) confound-resolver; ADR-017 speed doctrine",
        "assumptions": assumptions_block(),
        "plants": [p.as_dict() for p in PLANTS],
        "logs_considered": [Path(p).name for p in log_paths],
        # NAMED, always, with the reason. A skipped log is a hole in the denominator, and the one
        # thing this study may not do is report a table without saying what is missing from it.
        "logs_skipped": skipped,
        "flights": flights,
        "tripwire": trip,
        "verdict": verdicts(flights, trip, bar),
        "transfer_gap_register": TRANSFER_GAPS,
    }


def _cf_summary(rows: Sequence[dict], bar: float) -> dict:
    """Per-candidate and per-plant lead requirements, reported TWICE: physically and legally.

    WHY TWICE (QA finding M2, 2026-08-26). The legality vet uses the policy's own swept-path tree
    check, `GeofenceMap.segment_clearance`, which is XY-ONLY -- `geofence.py` says in its own
    comment that `is_safe_3d` is the altitude-aware query. On lane x = 15 the drone sits up to
    1.99 m INSIDE an orchard-row exclusion column horizontally, at 15 m altitude over a 3.5 m
    canopy, so at leads 0.5-1.75 s even BRAKE (a setpoint at the vehicle's own position) is booked
    illegal. Folding that into one number reported "the encounter first resolves at 2.0 s of lead"
    when the PHYSICS resolves it at 1.25 s (angle_max_ceiling, sidestep_ahead_+/-90, CPA 3.33 /
    3.40 m) -- a 60 % overstatement of any second-sensor horizon spec derived from it.

    So: `*_physically_*` is what the plant and the lead can do, and `*_legally_*` additionally
    requires a setpoint the current policy would have been allowed to command. The gap between them
    is a statement about the tree vet, not about the aircraft, and each row names which of the two
    bound it in `binding_constraint`. Reporting only the legal number is what the deleted
    `and r["setpoint_legal"]` guard used to do silently."""
    out: Dict[str, dict] = {}
    for r in rows:
        c = out.setdefault(r["candidate"], {
            "min_physically_resolving_lead_s": None, "min_legally_resolving_lead_s": None,
            "min_clearing_lead_s": None, "best_cpa_m": None, "best_cpa_plant": None,
            "best_min_horizontal_threat_m": None, "worst_min_horizontal_threat_m": None,
            "ever_resolved_physically": False, "ever_resolved_legally": False,
            "ever_cleared": False, "legal_at_best": None, "band_exit_only": True,
            "deferrals": 0, "band_exits": 0})
        if r["band_exit"]:
            c["band_exits"] += 1
        else:
            c["band_exit_only"] = False
        # Only a cell that STAYED IN BAND may set the headline CPA: a band-exit cell's gt_cpa is
        # the last in-band instant, not the separation at the crossing (C3).
        if not r["band_exit"] and r["gt_cpa_m"] is not None and (
                c["best_cpa_m"] is None or r["gt_cpa_m"] > c["best_cpa_m"]):
            c["best_cpa_m"] = r["gt_cpa_m"]
            c["best_cpa_plant"] = r["plant"]
            c["legal_at_best"] = r["setpoint_legal"]
        # BOTH ends of the band-free minimum. The best-case reading follows the same convention as
        # `best_cpa_m`, but for a BAND-EXIT candidate the best case is exactly the number that
        # flatters it -- a climb commanded 3 s early never gets near the bird, and printing only
        # that would re-create the optimism C3 was raised about one level up.
        mh = r["min_horizontal_threat_m"]
        if mh is not None:
            if (c["best_min_horizontal_threat_m"] is None
                    or mh > c["best_min_horizontal_threat_m"]):
                c["best_min_horizontal_threat_m"] = mh
            if (c["worst_min_horizontal_threat_m"] is None
                    or mh < c["worst_min_horizontal_threat_m"]):
                c["worst_min_horizontal_threat_m"] = mh
        if r["cleared"]:
            c["ever_cleared"] = True
            if c["min_clearing_lead_s"] is None or r["lead_s"] < c["min_clearing_lead_s"]:
                c["min_clearing_lead_s"] = r["lead_s"]
            if not r["resolved_physically"]:
                c["deferrals"] += 1
        if r["resolved_physically"]:
            c["ever_resolved_physically"] = True
            if (c["min_physically_resolving_lead_s"] is None
                    or r["lead_s"] < c["min_physically_resolving_lead_s"]):
                c["min_physically_resolving_lead_s"] = r["lead_s"]
        if r["resolved_legally"]:
            c["ever_resolved_legally"] = True
            if (c["min_legally_resolving_lead_s"] is None
                    or r["lead_s"] < c["min_legally_resolving_lead_s"]):
                c["min_legally_resolving_lead_s"] = r["lead_s"]

    def by_plant(pred) -> Dict[str, float]:
        acc: Dict[str, float] = {}
        for r in rows:
            if not pred(r):
                continue
            cur = acc.get(r["plant"])
            if cur is None or r["lead_s"] < cur:
                acc[r["plant"]] = r["lead_s"]
        return acc

    phys = [r for r in rows if r["resolved_physically"]]
    legal = [r for r in rows if r["resolved_legally"]]
    return {"per_candidate": out,
            "any_resolved_physically": bool(phys),
            "any_resolved_legally": bool(legal),
            "min_physically_resolving_lead_s": min((r["lead_s"] for r in phys), default=None),
            "min_legally_resolving_lead_s": min((r["lead_s"] for r in legal), default=None),
            # The numbers ADR-017's speed doctrine is priced against. Take the PHYSICAL one for a
            # sensor-horizon spec (it is a claim about the aircraft) and the LEGAL one for what
            # today's policy could actually command.
            "min_physically_resolving_lead_by_plant_s": by_plant(
                lambda r: r["resolved_physically"]),
            "min_legally_resolving_lead_by_plant_s": by_plant(lambda r: r["resolved_legally"]),
            "resolving_plants_physically": sorted({r["plant"] for r in phys}),
            "n_physically_resolving_but_illegal": sum(
                1 for r in rows if r["resolved_physically"] and not r["setpoint_legal"]),
            "any_cleared": any(r["cleared"] for r in rows),
            "n_deferrals": sum(1 for r in rows
                               if r["cleared"] and not r["resolved_physically"]),
            "n_band_exits": sum(1 for r in rows if r["band_exit"]),
            "bar_m": bar}


